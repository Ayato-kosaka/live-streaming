"""**issue を「誰待ちか」で仕分ける札と、あやとに本当に届く書きかた。**

ここには外に出る口が1つも無い。判定だけを置いてある。
使うのは `python/ticket_stock.py`（毎週の棚卸し）と、
機械で issue を立てる3本（`donor_calls` / `ingest_down` / `bake_down`）。

## なぜ札が要るか

2026-09-19 の時点で、開いている issue 25本に**ラベルが1つも付いていなかった。**
誰待ちかは題名の【】でしか分からず、【あやとの操作】と書いてあるものと
【親】と書いてあるものが同じ見た目で並んでいた。

**題名は人が読むもので、機械からは読めない。** 機械から読めないと、
「あやと待ちが何本あるか」を誰も数えられない。数えられないものは溜まる。

| 札 | 意味 | 誰が動かすと進むか |
| --- | --- | --- |
| `待ち-あやと` | 鍵・権限・コンソールの操作・「どうしたいか」の答え | **あやとだけ** |
| `待ち-システム` | 直せる。まだ手が回っていないだけ | **システム開発担当**（この AI） |
| `旅のあと` | 旅が終わるまで着手すると壊れる | 時間 |

**迷ったら `待ち-システム` に倒す。** あやと待ちに置くと、**開発の手が
止まったまま「待っている」ことにできてしまう。**

**札は「こちら」と書かない。** 読む人（あやと）から見て「こちら」がどちらか
分からない。あやとの言葉（2026-09-23）:

> こちらって表現いまいちすぎる。。。

## なぜメンションが要るか

**題名に【あやとの操作】と書いても、通知は1通も飛ばない。**
2026-09-19 にあやとから「これ、私にメンションしてほしいと言ったはず」と
言われたのが #478 で、**あれは人ではなく機械（`github-actions[bot]`）が
立てたもの**だった。機械が立てる issue は、こちらが手で書き足すことが
できない——**立てる側のコードに入っていなければ、永遠に入らない。**

## 全部にメンションを入れない

毎晩鳴るものに毎晩メンションを付けると、そのうち誰も読まなくなる。
**あやとにしかできないことを待っているものだけ**に付ける。

| 立てるもの | メンションするか | なぜ |
| --- | --- | --- |
| `donor_calls`（紐付け待ち） | **する** | 対応表を触れるのはあやただけ |
| `ingest_down` の `session_expired` | **する** | cookie を入れ直せるのはあやただけ |
| `ingest_down` の「何日も入っていない」 | しない | システム側で流し直せば入ることがある |
| `bake_down`（焼き直しの赤） | しない | システム側で直せる |
| 毎週の棚卸し | **あやと待ちが在るときだけ** | 0本の週に鳴らす意味が無い |

## 「書いてある」と「飛ぶ」は別

GitHub はコードブロックの中・引用（`>`）の中・バッククォートで囲んだ
`@名前` を**メンションとして扱わない。** 字として在るのに1通も飛ばない、
がいちばん起きやすい外し方なので、`mention_live()` で機械に見させる。

**そして、本文を書き換えても通知は飛ばない。** 飛ぶのは
**issue を開いたとき**と**コメントを足したとき**だけ。ここが効いてくるのは
`donor_calls` や `bake_down` のように**同じ1本の本文を毎晩差し替える**形で、
本文にメンションを入れておくだけでは、開いた最初の1回しか届かない。
かといって毎晩コメントを足すと雑音になる。**変わり目でだけ鳴らす**のが
`should_ping()`。

## 答えが来たら、札は**ひとりでに**裏返る

あやとの言葉（2026-10-13）:

> あと、返信したのに「あやと待ち」にするのはやめて欲しい

2026-10-13 まで、このリポジトリに **`待ち-あやと` を外すものが1つも無かった。**
札は付くだけで、外れない。あやとが答えても、セッションが気づいて手で外すまで
「あやと待ち」のまま並ぶ。**人の記憶に頼っている時点で、仕組みが無いのと同じ**
（#808 #809 で実際にそうなった）。

`flip_verdict()` が、コメント1本を見て**裏返すかどうか**だけを答える。

### 見分けの肝: **著者では分からない**

**セッションが書くコメントも、GitHub 上の著者は `Ayato-kosaka`**
（セッションはあやと本人のトークンで書いている）。だから
「著者があやとなら本人」は**誤爆する。** 直近100本の実測（2026-10-13）:

| 著者 | 本数 | うち署名つき（＝セッション） |
| --- | ---: | ---: |
| `Ayato-kosaka`（type=User） | 74 | **55** |
| `github-actions[bot]`（type=Bot） | 26 | — |

見分けの印は**末尾の署名**（`SIGNATURE`）だけ。55本とも**最後の行**が署名で、
**署名のうしろに1文字も無かった**（`---` が前に付くのも55本とも同じ）。

### 迷ったら**裏返す**ほうへ倒す

この見分けは壊れうる。壊れたときに**どちら側へ転ぶか**を先に決めてある。

| 壊れ方 | どう転ぶか | 代償 |
| --- | --- | --- |
| こちらが署名を付け忘れた | **裏返る**（あやと本人と読む） | 札がシステム側に移るだけ。**読むのはシステム自身**で、次に聞くときに `待ち-あやと` を付け直す |
| あやとが引用でこちらの署名を貼った | **裏返る**（`signed_by_system()` が引用・囲いの中の署名を数えないため） | 無し |
| あやとが署名そのものを本文の最後に貼った | 裏返らない | **静かな失敗。** これだけは `missed_flips()` が拾う |

**裏返らなかったのは静かな失敗**で、誰も赤くならない——あやとの目には
「答えたのに、まだあやと待ち」としか映らない。いま起きている不具合そのもの
なので、**疑わしいものは裏返す側へ倒す。** `ticket_labels` の既定（迷ったら
`待ち-システム`）とも向きが同じ。

### それでも取りこぼす（発火しない・札が競合する）ぶんは、数えて拾う

`issue_comment` が届かなかった日・あやとが札より先に答えた issue・
口が断った回は、どの判定を書いても裏返らない。**「裏返るはずだったのに
裏返っていない」は、札とコメントだけで数えられる**ので、`missed_flips()` に
してある。見回りが毎日これを当てる（`.github/workflows/wait_flip.yml`）。

**遡るのは1週間ぶん**（`SWEEP_WINDOW_DAYS`）。見回りの仕事は「届かなかった
ぶんを翌日までに拾う」ことで、**昔のコメントを読み直して札を付け替えること
ではない。** 窓を外して本番に当てたら、2026-09-22 にあやとが書いた備忘1行
（#147。答えではなく控え）で、審査待ちの issue が「システムの番」になった。
"""

import re
from datetime import datetime, timedelta, timezone

# 待ちの相手を表す3つの札。**この3つだけ。** 増やすと、どれを付ければいいか
# 迷う面が増えて、結局付かなくなる
WAIT_AYATO = "待ち-あやと"
WAIT_US = "待ち-システム"
AFTER_TRIP = "旅のあと"

# 並べる順。**あやと待ちが先頭。** 棚卸しの本文も一覧もこの順で出す
WAITS = (WAIT_AYATO, WAIT_US, AFTER_TRIP)

# 札の見た目（色・説明）。無ければ作る。既に居る札とは別の色にする
# （`donor-calls` d93f0b / `ingest-down` b60205 / `bake-down` 5319e7 /
#  `ship-down` 006b75）
WAIT_STYLE = {
    WAIT_AYATO: ("fbca04", "あやとにしかできないことを待っている"),
    WAIT_US: ("0e8a16", "システム開発担当が直せる。まだ手が回っていない"),
    AFTER_TRIP: ("1d76db", "旅が終わるまで着手すると壊れる"),
}

# あやとの GitHub の名乗り。**ここ1か所だけに書く。**
# 散らすと、変わった日に半分だけ直る
HANDLE = "@Ayato-kosaka"

# あやとの GitHub の login。**`HANDLE` から導く。**
# 2か所に書くと、変わった日に半分だけ直る
OWNER_LOGIN = HANDLE.lstrip("@")

# **こちら（セッション）が書いたコメントの末尾に必ず入る署名。**
# セッションもあやと本人のトークンで書くので、著者では見分けがつかない。
# **この1行だけが見分け。** 直近100本の実測で、セッションの55本とも
# これが最後の行だった（うしろに1文字も無い）
SIGNATURE = "_Generated by [Claude Code](https://claude.ai/code)_"

# 見回り（`missed_flips()`）が遡る日数。
#
# **遡りすぎない。** 見回りの仕事は「その場の裏返しが届かなかったぶんを、
# 翌日までに拾う」ことで、**昔のコメントを読み直して札を付け替えることではない。**
# 窓を外すと、2026-09-22 にあやとが書いた備忘1行（#147。答えではなく控え）で
# 審査待ちの issue が「システムの番」になる。見回りは毎日走るので、
# 1週間あれば見回り自体が何日か落ちていても追いつく
SWEEP_WINDOW_DAYS = 7

# `flip_verdict()` が返す答え。**裏返すのは `FLIP` のときだけ。**
# 残りは「なぜ裏返さなかったか」で、**0件の回に何を見たかを出す**ために
# 名前を分けてある（`docs/island-standards.md` §15）
FLIP = "flip"
SKIP_NOT_CREATED = "not-created"
SKIP_NO_WAIT = "no-wait-ayato"
SKIP_BOT = "bot"
SKIP_NOT_OWNER = "not-owner"
SKIP_SIGNED = "signed"

# 要約欄に出す1行。**本文も題名も出さない**（公開のログに素性を流さない）
VERDICT_WHY = {
    FLIP: "あやと本人が答えた → 待ち-システムへ裏返す",
    SKIP_NOT_CREATED: "新しいコメントではない",
    SKIP_NO_WAIT: "待ち-あやと が付いていない",
    SKIP_BOT: "機械が書いたコメント",
    SKIP_NOT_OWNER: "あやと以外が書いたコメント",
    SKIP_SIGNED: "システムが書いたコメント（末尾に署名が在る）",
}

# コードブロックの囲い（``` か ~~~）。中に入った `@名前` は飛ばない
_FENCE = re.compile(r"^\s*(```|~~~)")

# 行の頭の引用・箇条書きの記号を落としてから見る。
# `> @Ayato-kosaka` は引用なので飛ばないが、`- @Ayato-kosaka` は飛ぶ
_QUOTE = re.compile(r"^\s*>")

# 4つ以上の空白で始まる行は、GitHub ではコードとして描かれる
_INDENT = re.compile(r"^(?: {4,}|\t)")


def wait_of(labels) -> str:
    """付いている札から、**待ちの相手**を1つ選ぶ。

    GitHub が返す形（`[{"name": ...}, ...]`）でも、名前だけの並びでも読む。

    2つ以上付いていたら `WAITS` の順で先に来るほうを採る。**黙って両方
    数えない**——数えると本数の合計が開いている本数と合わなくなって、
    分母が壊れる（`docs/island-standards.md` §15）。

    Args:
        labels: issue に付いている札

    Returns:
        `WAIT_AYATO` / `WAIT_US` / `AFTER_TRIP` のどれか。
        1つも付いていなければ空文字
    """
    names = set()
    for x in labels or []:
        name = x.get("name") if isinstance(x, dict) else x
        if isinstance(name, str):
            names.add(name)
    for w in WAITS:
        if w in names:
            return w
    return ""


def mention_live(text: str) -> bool:
    """本文の中に、**通知として飛ぶ形の** `@Ayato-kosaka` が在るか。

    字として在るだけでは足りない。GitHub は次の中の `@名前` を
    メンションとして扱わない:

    - コードブロック（``` / ~~~ の中、4つ以上の空白で始まる行）
    - 引用（行頭の `>`）
    - バッククォートで囲んだところ（`` `@Ayato-kosaka` ``）

    **「書いたのに飛ばない」がいちばん起きやすい外し方**なので、
    人の目ではなくここで見る。

    Args:
        text: issue の本文かコメント

    Returns:
        飛ぶ形で入っていれば True
    """
    fenced = False
    for line in (text or "").splitlines():
        if _FENCE.match(line):
            fenced = not fenced
            continue
        if fenced or _QUOTE.match(line) or _INDENT.match(line):
            continue
        # 行の中のバッククォートで囲まれたところを落としてから探す
        bare = re.sub(r"`[^`]*`", "", line)
        if HANDLE in bare:
            return True
    return False


def should_ping(action: str, prev_body: str, needs_ayato: bool) -> bool:
    """**コメントで鳴らすか**を決める。GitHub を触らない素の関数。

    本文を書き換えても通知は飛ばない。飛ぶのは開いたときとコメントだけ。
    だから「鳴らす」は**コメントを1本足す**という意味になる。

    | いま | すること | なぜ |
    | --- | --- | --- |
    | あやと待ちではない | 鳴らさない | 毎晩鳴るものに毎晩メンションすると読まれなくなる |
    | `create` | 鳴らさない | **本文にメンションを入れて開く**ので、開いた時点で飛ぶ |
    | `reopen` | **鳴らす** | 状態を変えるだけでは1通も飛ばない |
    | `update` で、前の本文にメンションが無かった | **鳴らす** | ここで初めてあやと待ちになった |
    | `update` で、前の本文にもう在った | 鳴らさない | 同じことを毎晩言わない |

    Args:
        action: `decide()` が返した動き（create / reopen / update / close / noop）
        prev_body: いま GitHub に載っている本文（無ければ空文字）
        needs_ayato: この用事が、あやとにしかできないものか

    Returns:
        コメントを足すなら True
    """
    if not needs_ayato:
        return False
    if action == "create":
        return False
    if action == "reopen":
        return True
    if action == "update":
        return not mention_live(prev_body or "")
    return False


def ping_text(what: str) -> str:
    """鳴らすときのコメント。**1行だけ。**

    本文に何が書いてあるかはすぐ上に出ているので、繰り返さない。
    `HANDLE` を行の先頭に置くのは、囲いや引用に巻き込まれないため。

    Args:
        what: 何を待っているか（「投げ銭の紐付け」など。1行で書ける短いもの）

    Returns:
        コメントの本文
    """
    return f"{HANDLE} {what}。ここはあやとの手が要ります。\n"


def signed_by_system(body: str) -> bool:
    """本文の**末尾が、こちらの署名そのもの**か。

    `mention_live()` と同じ考え方——**「字として在る」と「効いている」は別。**
    引用（`>`）・囲い（``` / ~~~）・4つ空白の中にある署名は数えない。
    あやとがこちらのコメントを丸ごと引用して答えたとき、そこに写った署名で
    「これはシステムのコメントだ」と読んでしまうと、**裏返るべきものが
    裏返らない**（静かな失敗）。

    **末尾であることも要る。** 直近100本の実測（2026-10-13）で、署名を持つ
    55本はぜんぶ最後の行が署名で、うしろに1文字も無かった。署名のあとに
    何か書いてあるものは、こちらが書いたものとは形が違う。

    Args:
        body: コメントの本文

    Returns:
        こちらが書いたものと読めるなら True
    """
    fenced = False
    signed = False
    for line in (body or "").splitlines():
        if _FENCE.match(line):
            # 囲いが開いても閉じても、そこから下が末尾になる
            fenced = not fenced
            signed = False
            continue
        if fenced or _QUOTE.match(line) or _INDENT.match(line):
            # 引用・囲い・字下げの中の署名は数えない。
            # **ただし字が在れば「末尾の署名」ではなくなる**
            if line.strip():
                signed = False
            continue
        if line.strip() == SIGNATURE:
            signed = True
        elif line.strip():
            signed = False
    return signed


def flip_verdict(action: str, login: str, user_type: str,
                 body: str, labels) -> str:
    """コメント1本を見て、**待ち札を裏返すか**を決める。GitHub を触らない。

    **外に問い合わせない。** `issue_comment` の受け取りに在るものだけで
    決まるので、対象外のコメントでは口を1回も叩かずに済む。

    見る順は「札 → 誰 → 何を書いたか」ではなく、**`action` → 札 → 機械 →
    あやと以外 → 署名**。いちばん多いのは「札が付いていない issue への
    コメント」なので、そこで早く帰る。

    Args:
        action: `issue_comment` の `action`（`created` 以外は見ない）
        login: 書いた人の login
        user_type: `User` か `Bot`
        body: コメントの本文
        labels: その issue に**いま**付いている札

    Returns:
        `FLIP` なら裏返す。それ以外は `VERDICT_WHY` に理由が入っている
    """
    if action != "created":
        return SKIP_NOT_CREATED
    if wait_of(labels) != WAIT_AYATO:
        return SKIP_NO_WAIT
    # `type` は `User` / `Bot`。login の `[bot]` も見るのは、`type` を
    # 載せてこない経路（古い受け取り・こしらえた入力）でも落ちないため
    if (user_type or "") == "Bot" or (login or "").endswith("[bot]"):
        return SKIP_BOT
    if (login or "").lower() != OWNER_LOGIN.lower():
        return SKIP_NOT_OWNER
    if signed_by_system(body):
        return SKIP_SIGNED
    return FLIP


def flip_from_event(event) -> tuple:
    """`issue_comment` の受け取り一式から、答えと**相手**を取り出す。

    ワークフローに判定を持たせないための口。あちらがするのは
    「受け取りを読む・返ってきた札を PUT する」だけ。

    Args:
        event: `$GITHUB_EVENT_PATH` の中身

    Returns:
        （`flip_verdict()` の答え, issue の番号, いま付いている札）
    """
    ev = event or {}
    issue = ev.get("issue") or {}
    comment = ev.get("comment") or {}
    user = comment.get("user") or {}
    verdict = flip_verdict(ev.get("action"), user.get("login"),
                           user.get("type"), comment.get("body"),
                           issue.get("labels"))
    return verdict, issue.get("number"), issue.get("labels") or []


def flipped_labels(labels) -> list:
    """`待ち-あやと` を `待ち-システム` に置き換えた、**札の一覧ぜんぶ**。

    GitHub の `PUT /issues/{n}/labels` に渡す形。1本ずつ消して付けるより
    口が1回で済み、**日本語の札の名前を URL の道に入れずに済む。**

    **他の札は順番ごと残す。** ここで取りこぼすと、`整備` や `donor-calls` が
    黙って消える。両方付いていた issue では `待ち-システム` を1つにまとめる。

    Args:
        labels: いま付いている札

    Returns:
        置き換えたあとの名前の並び。`待ち-あやと` が無ければそのまま
    """
    names = []
    for x in labels or []:
        name = x.get("name") if isinstance(x, dict) else x
        if isinstance(name, str) and name not in names:
            names.append(name)
    if WAIT_AYATO not in names:
        return names
    out = []
    for n in names:
        if n == WAIT_AYATO:
            n = WAIT_US
        if n in out:
            continue
        out.append(n)
    return out


def missed_flips(issues, now=None,
                 within_days=SWEEP_WINDOW_DAYS) -> list:
    """**裏返るはずだったのに、裏返っていないもの**を挙げる。

    `flip_verdict()` は、コメントが来たその場でしか効かない。
    届かなかった回（発火しない・口が断った・あやとが札より先に答えた）は、
    **誰も赤くならないまま「あやと待ち」で並び続ける。** これが
    2026-10-13 にあやとから来た一言そのもの。

    拾い方は札とコメントだけで足りる——**`待ち-あやと` なのに、いちばん
    新しいコメントがあやと本人**なら、それは裏返り損ねたもの。
    その場の判定と同じ `flip_verdict()` を当てるので、見分けは1か所のまま。

    **遡るのは `SWEEP_WINDOW_DAYS` 日ぶんだけ。** それより前のコメントは、
    その場の裏返しが在るより前の話で、いま読み直して札を付け替えるのは
    「取りこぼしを拾う」ではなく**歴史の書き換え**になる。

    Args:
        issues: `{"number", "labels",
            "comments": [{"login","type","body","at"}, …]}` の並び。
            **`comments` は古い順**（GitHub が返す順）。`at` は ISO8601
        now: いま（渡さなければ現在時刻）
        within_days: 遡る日数。`None` なら窓を外す（見張り用）

    Returns:
        裏返すべき issue の番号
    """
    now = now or datetime.now(timezone.utc)
    out = []
    for it in issues or []:
        labels = it.get("labels")
        if wait_of(labels) != WAIT_AYATO:
            continue
        comments = it.get("comments") or []
        if not comments:
            continue
        last = comments[-1] or {}
        if flip_verdict("created", last.get("login"), last.get("type"),
                        last.get("body"), labels) != FLIP:
            continue
        if within_days is not None and not _within(last.get("at"), now,
                                                   within_days):
            continue
        out.append(it.get("number"))
    return out


def _within(at: str, now: datetime, days: int) -> bool:
    """`at`（ISO8601）が、いまから `days` 日の内側か。

    **日付が読めなかったら内側に倒す。** 読めないものを黙って外すと、
    見回りが何も拾わないまま緑で終わる（§15 の「0件」）。
    """
    if not at:
        return True
    try:
        t = datetime.fromisoformat(str(at).replace("Z", "+00:00"))
    except ValueError:
        return True
    if t.tzinfo is None:
        t = t.replace(tzinfo=timezone.utc)
    return (now - t) <= timedelta(days=days)
