# 1週間あれば見回り自体が何日か落ちていても追いつく
SWEEP_WINDOW_DAYS = 7

# `flip_verdict()` が返す答え。**裏返すのは `FLIP` のときだけ。**
# 残りは「なぜ裏返さなかったか」で、**0件の回に何を見たかを出す**ために
# 名前を分けてある（`docs/island-standards.md` §15）
FLIP = "flip"
SKIP_NOT_CREATED = "not-created"
SKIP_NO_WAIT = "no-wait-ayato"
SKIP_BOT = "bot"
SKIP_NOT_OWNER = "not-owner"
SKIP_SIGNED = "signed"

# 要約欄に出す1行。**本文も題名も出さない**（公開のログに素性を流さない）
VERDICT_WHY = {
    FLIP: "あやと本人が答えた → 待ち-システムへ裏返す",
    SKIP_NOT_CREATED: "新しいコメントではない",
    SKIP_NO_WAIT: "待ち-あやと が付いていない",
    SKIP_BOT: "機械が書いたコメント",
    SKIP_NOT_OWNER: "あやと以外が書いたコメント",
    SKIP_SIGNED: "システムが書いたコメント（末尾に署名が在る）",
}

# コードブロックの囲い（``` か ~~~）。中に入った `@名前` は飛ばない
_FENCE = re.compile(r"^\s*(```|~~~)")

# 行の頭の引用・箇条書きの記号を落としてから見る。
# `> @Ayato-kosaka` は引用なので飛ばないが、`- @Ayato-kosaka` は飛ぶ
_QUOTE = re.compile(r"^\s*>")

# 4つ以上の空白で始まる行は、GitHub ではコードとして描かれる
_INDENT = re.compile(r"^(?: {4,}|\t)")


def wait_of(labels) -> str:
    """付いている札から、**待ちの相手**を1つ選ぶ。

    GitHub が返す形（`[{"name": ...}, ...]`）でも、名前だけの並びでも読む。

    2つ以上付いていたら `WAITS` の順で先に来るほうを採る。**黙って両方
    数えない**——数えると本数の合計が開いている本数と合わなくなって、
    分母が壊れる（`docs/island-standards.md` §15）。

    Args:
        labels: issue に付いている札

    Returns:
        `WAIT_AYATO` / `WAIT_US` / `AFTER_TRIP` のどれか。
        1つも付いていなければ空文字
    """
    names = set()
    for x in labels or []:
        name = x.get("name") if isinstance(x, dict) else x
        if isinstance(name, str):
            names.add(name)
    for w in WAITS:
        if w in names:
            return w
    return ""


def mention_live(text: str) -> bool:
    """本文の中に、**通知として飛ぶ形の** `@Ayato-kosaka` が在るか。

    字として在るだけでは足りない。GitHub は次の中の `@名前` を
    メンションとして扱わない:

    - コードブロック（``` / ~~~ の中、4つ以上の空白で始まる行）
    - 引用（行頭の `>`）
    - バッククォートで囲んだところ（`` `@Ayato-kosaka` ``）

    **「書いたのに飛ばない」がいちばん起きやすい外し方**なので、
    人の目ではなくここで見る。

    Args:
        text: issue の本文かコメント

    Returns:
        飛ぶ形で入っていれば True
    """
    fenced = False
    for line in (text or "").splitlines():
        if _FENCE.match(line):
            fenced = not fenced
            continue
        if fenced or _QUOTE.match(line) or _INDENT.match(line):
            continue
        # 行の中のバッククォートで囲まれたところを落としてから探す
        bare = re.sub(r"`[^`]*`", "", line)
        if HANDLE in bare:
            return True
    return False


def should_ping(action: str, prev_body: str, needs_ayato: bool) -> bool:
    """**コメントで鳴らすか**を決める。GitHub を触らない素の関数。

    本文を書き換えても通知は飛ばない。飛ぶのは開いたときとコメントだけ。
    だから「鳴らす」は**コメントを1本足す**という意味になる。

    | いま | すること | なぜ |
    | --- | --- | --- |
    | あやと待ちではない | 鳴らさない | 毎晩鳴るものに毎晩メンションすると読まれなくなる |
    | `create` | 鳴らさない | **本文にメンションを入れて開く**ので、開いた時点で飛ぶ |
    | `reopen` | **鳴らす** | 状態を変えるだけでは1通も飛ばない |
    | `update` で、前の本文にメンションが無かった | **鳴らす** | ここで初めてあやと待ちになった |
    | `update` で、前の本文にもう在った | 鳴らさない | 同じことを毎晩言わない |

    Args:
        action: `decide()` が返した動き（create / reopen / update / close / noop）
        prev_body: いま GitHub に載っている本文（無ければ空文字）
        needs_ayato: この用事が、あやとにしかできないものか

    Returns:
        コメントを足すなら True
    """
    if not needs_ayato:
        return False
    if action == "create":
        return False
    if action == "reopen":
        return True
    if action == "update":
        return not mention_live(prev_body or "")
    return False


def ping_text(what: str) -> str:
    """鳴らすときのコメント。**1行だけ。**

    本文に何が書いてあるかはすぐ上に出ているので、繰り返さない。
    `HANDLE` を行の先頭に置くのは、囲いや引用に巻き込まれないため。

    Args:
        what: 何を待っているか（「投げ銭の紐付け」など。1行で書ける短いもの）

    Returns:
        コメントの本文
    """
    return f"{HANDLE} {what}。ここはあやとの手が要ります。\n"


def signed_by_system(body: str) -> bool:
    """本文の**末尾が、こちらの署名そのもの**か。

    `mention_live()` と同じ考え方——**「字として在る」と「効いている」は別。**
    引用（`>`）・囲い（``` / ~~~）・4つ空白の中にある署名は数えない。
    あやとがこちらのコメントを丸ごと引用して答えたとき、そこに写った署名で
    「これはシステムのコメントだ」と読んでしまうと、**裏返るべきものが
    裏返らない**（静かな失敗）。

    **末尾であることも要る。** 直近100本の実測（2026-10-13）で、署名を持つ
    55本はぜんぶ最後の行が署名で、うしろに1文字も無かった。署名のあとに
    何か書いてあるものは、こちらが書いたものとは形が違う。

    Args:
        body: コメントの本文

    Returns:
        こちらが書いたものと読めるなら True
    """
    fenced = False
    signed = False
    for line in (body or "").splitlines():
        if _FENCE.match(line):
            # 囲いが開いても閉じても、そこから下が末尾になる
            fenced = not fenced
            signed = False
            continue
        if fenced or _QUOTE.match(line) or _INDENT.match(line):
            # 引用・囲い・字下げの中の署名は数えない。
            # **ただし字が在れば「末尾の署名」ではなくなる**
            if line.strip():
                signed = False
            continue
        if line.strip() == SIGNATURE:
            signed = True
        elif line.strip():
            signed = False
    return signed


def flip_verdict(action: str, login: str, user_type: str,
                 body: str, labels) -> str:
    """コメント1本を見て、**待ち札を裏返すか**を決める。GitHub を触らない。

    **外に問い合わせない。** `issue_comment` の受け取りに在るものだけで
    決まるので、対象外のコメントでは口を1回も叩かずに済む。

    見る順は「札 → 誰 → 何を書いたか」ではなく、**`action` → 札 → 機械 →
    あやと以外 → 署名**。いちばん多いのは「札が付いていない issue への
    コメント」なので、そこで早く帰る。

    Args:
        action: `issue_comment` の `action`（`created` 以外は見ない）
        login: 書いた人の login
        user_type: `User` か `Bot`
        body: コメントの本文
        labels: その issue に**いま**付いている札

    Returns:
        `FLIP` なら裏返す。それ以外は `VERDICT_WHY` に理由が入っている
    """
    if action != "created":
        return SKIP_NOT_CREATED
    if wait_of(labels) != WAIT_AYATO:
        return SKIP_NO_WAIT
    # `type` は `User` / `Bot`。login の `[bot]` も見るのは、`type` を
    # 載せてこない経路（古い受け取り・こしらえた入力）でも落ちないため
    if (user_type or "") == "Bot" or (login or "").endswith("[bot]"):
        return SKIP_BOT
    if (login or "").lower() != OWNER_LOGIN.lower():
        return SKIP_NOT_OWNER
    if signed_by_system(body):
        return SKIP_SIGNED
    return FLIP


def flip_from_event(event) -> tuple:
    """`issue_comment` の受け取り一式から、答えと**相手**を取り出す。

    ワークフローに判定を持たせないための口。あちらがするのは
    「受け取りを読む・返ってきた札を PUT する」だけ。

    Args:
        event: `$GITHUB_EVENT_PATH` の中身

    Returns:
        （`flip_verdict()` の答え, issue の番号, いま付いている札）
    """
    ev = event or {}
    issue = ev.get("issue") or {}
    comment = ev.get("comment") or {}
    user = comment.get("user") or {}
    verdict = flip_verdict(ev.get("action"), user.get("login"),
                           user.get("type"), comment.get("body"),
                           issue.get("labels"))
    return verdict, issue.get("number"), issue.get("labels") or []


def flipped_labels(labels) -> list:
    """`待ち-あやと` を `待ち-システム` に置き換えた、**札の一覧ぜんぶ**。

    GitHub の `PUT /issues/{n}/labels` に渡す形。1本ずつ消して付けるより
    口が1回で済み、**日本語の札の名前を URL の道に入れずに済む。**

    **他の札は順番ごと残す。** ここで取りこぼすと、`整備` や `donor-calls` が
    黙って消える。両方付いていた issue では `待ち-システム` を1つにまとめる。

    Args:
        labels: いま付いている札

    Returns:
        置き換えたあとの名前の並び。`待ち-あやと` が無ければそのまま
    """
    names = []
    for x in labels or []:
        name = x.get("name") if isinstance(x, dict) else x
        if isinstance(name, str) and name not in names:
            names.append(name)
    if WAIT_AYATO not in names:
        return names
    out = []
    for n in names:
        if n == WAIT_AYATO:
            n = WAIT_US
        if n in out:
            continue
        out.append(n)
    return out


def missed_flips(issues, now=None,
                 within_days=SWEEP_WINDOW_DAYS) -> list:
    """**裏返るはずだったのに、裏返っていないもの**を挙げる。

    `flip_verdict()` は、コメントが来たその場でしか効かない。
    届かなかった回（発火しない・口が断った・あやとが札より先に答えた）は、
    **誰も赤くならないまま「あやと待ち」で並び続ける。** これが
    2026-10-13 にあやとから来た一言そのもの。

    拾い方は札とコメントだけで足りる——**`待ち-あやと` なのに、いちばん
    新しいコメントがあやと本人**なら、それは裏返り損ねたもの。
    その場の判定と同じ `flip_verdict()` を当てるので、見分けは1か所のまま。

    **遡るのは `SWEEP_WINDOW_DAYS` 日ぶんだけ。** それより前のコメントは、
    その場の裏返しが在るより前の話で、いま読み直して札を付け替えるのは
    「取りこぼしを拾う」ではなく**歴史の書き換え**になる。

    Args:
        issues: `{"number", "labels",
            "comments": [{"login","type","body","at"}, …]}` の並び。
            **`comments` は古い順**（GitHub が返す順）。`at` は ISO8601
        now: いま（渡さなければ現在時刻）
        within_days: 遡る日数。`None` なら窓を外す（見張り用）

    Returns:
        裏返すべき issue の番号
    """
    now = now or datetime.now(timezone.utc)
    out = []
    for it in issues or []:
        labels = it.get("labels")
        if wait_of(labels) != WAIT_AYATO:
            continue
        comments = it.get("comments") or []
        if not comments:
            continue
        last = comments[-1] or {}
        if flip_verdict("created", last.get("login"), last.get("type"),
                        last.get("body"), labels) != FLIP:
            continue
        if within_days is not None and not _within(last.get("at"), now,
                                                   within_days):
            continue
        out.append(it.get("number"))
    return out


def _within(at: str, now: datetime, days: int) -> bool:
    """`at`（ISO8601）が、いまから `days` 日の内側か。

    **日付が読めなかったら内側に倒す。** 読めないものを黙って外すと、
    見回りが何も拾わないまま緑で終わる（§15 の「0件」）。
    """
    if not at:
        return True
    try:
        t = datetime.fromisoformat(str(at).replace("Z", "+00:00"))
    except ValueError:
        return True
    if t.tzinfo is None:
        t = t.replace(tzinfo=timezone.utc)
    return (now - t) <= timedelta(days=days)


# ---- 札が付いたら、機械が鳴らす（`.github/workflows/wait_ping.yml`）------
#
# あやと（2026-10-28・チャット）:
#
# > なぜ通知してない？運用徹底してよ
#
# 札を付けたのに `call_ayato.yml` を回し忘れて、4本が「返事待ち」のまま
# 黙っていた（`docs/island-misses.md` #306）。**札を付ける人と、鳴らす人が
# 別の手順だった**のが根で、手順に書き足しても同じことが起きる。
# だから**札そのものを引き金にする。**

# `wait_ping_verdict()` が返す答え。**鳴らすのは `PING` のときだけ。**
# 残りは「なぜ鳴らさなかったか」で、0件の回に何を見たかを要約に出すために
# 名前を分けてある（`VERDICT_WHY` と同じ考え方。`docs/island-standards.md` §15）
PING = "ping"
QUIET_EVENT = "not-ask"
QUIET_OTHER_LABEL = "other-label"
QUIET_CLOSED = "closed"
QUIET_NO_WAIT = "no-wait-ayato"
QUIET_BOT = "bot"
QUIET_NOT_OWNER = "not-owner"
QUIET_NOT_SIGNED = "not-signed"
QUIET_ALREADY = "already-called"

# 要約欄に出す1行。**本文も題名も出さない**（公開のログに素性を流さない）
PING_WHY = {
    PING: "あやと待ちなのに、まだ呼んでいない → 呼ぶ",
    QUIET_EVENT: "札が付いた・システムが書き足した、のどちらでもない",
    QUIET_OTHER_LABEL: "付いた札が 待ち-あやと ではない",
    QUIET_CLOSED: "閉じた issue",
    QUIET_NO_WAIT: "待ち-あやと が付いていない",
    QUIET_BOT: "機械が書いたコメント",
    QUIET_NOT_OWNER: "あやとのアカウント以外が書いたコメント",
    QUIET_NOT_SIGNED: "署名の無いコメント。あやと本人の返事",
    QUIET_ALREADY: "もう呼んである。最後の書き込みのあとに、飛ぶメンションが在る",
}

# 札が付いて（書き足されて）から、書き込みの並びを読みに行くまで待つ秒数。
#
# **すぐ読むと、重なって2通鳴る。** 札を付けた人は、たいてい続けて問いを
# 書き足すか `call_ayato.yml` を回す。あちらの書き込みが載る前に読むと
# 「まだ呼んでいない」に見える。`call_ayato` は押してから書き込むまで
# 十数秒〜1分かかるので、それより長く待つ。
# 待つのは**鳴らす見込みがあるときだけ**（`wait_ping_trigger()` が通したあと）。
# 対象外のコメントは待たずに帰る
PING_SETTLE_SECONDS = 120


def _flat(c) -> dict:
    """書き込み1つを `{"login", "type", "body"}` にそろえる。

    GitHub が返す形（`{"user": {"login", "type"}, "body"}`）でも、
    そろえたあとの形でも読む。
    """
    c = c or {}
    user = c.get("user")
    if isinstance(user, dict):
        return {"login": user.get("login") or "", "type": user.get("type") or "",
                "body": c.get("body") or ""}
    return {"login": c.get("login") or "", "type": c.get("type") or "",
            "body": c.get("body") or ""}


def _is_owner(login) -> bool:
    """あやとのアカウントか。**セッションもこのアカウントで書く。**"""
    return (login or "").lower() == OWNER_LOGIN.lower()


def wait_ping_trigger(event_name: str, action: str, label, issue_labels,
                      comment=None, state: str = "open") -> str:
    """受け取り1つだけで決まるところ。**GitHub の口を1回も叩かない。**

    ここで `PING` が出たものだけが、待って（`PING_SETTLE_SECONDS`）
    書き込みの並びを読みに行く。いちばん多いのは「札の無い issue への
    コメント」なので、そこで早く帰る。

    | 受け取り | 鳴らす見込み |
    | --- | --- |
    | `issues` の `labeled` で、付いた札が `待ち-あやと` | **在る** |
    | `issues` の `opened` で、`待ち-あやと` を付けて開いた | **在る**（札つきで開いたとき、`labeled` が来ない日のため） |
    | `issue_comment` の `created` で、`待ち-あやと` の issue に**システムの署名つき**のコメント | **在る** |
    | それ以外（ほかの札・書き直し・閉じた issue・あやと本人の返事・機械・ほかの人） | 無い |

    **あやと本人の返事では鳴らさない。** 答えた人を呼んでも意味が無いし、
    答えた時点で札は `wait_flip` が裏返す。

    Args:
        event_name: `issues` か `issue_comment`（`$GITHUB_EVENT_NAME`）
        action: 受け取りの `action`
        label: `labeled` のとき付いた札（`{"name": …}` でも名前だけでも）
        issue_labels: その issue に付いている札
        comment: `issue_comment` のときのコメント（GitHub の形でも、そろえた形でも）
        state: issue の状態（`open` / `closed`）

    Returns:
        `PING` なら鳴らす見込みが在る。それ以外は `PING_WHY` に理由が入っている
    """
    if event_name == "issues":
        if action == "labeled":
            name = label.get("name") if isinstance(label, dict) else label
            if name != WAIT_AYATO:
                return QUIET_OTHER_LABEL
        elif action != "opened":
            return QUIET_EVENT
    elif event_name == "issue_comment":
        if action != "created":
            return QUIET_EVENT
    else:
        return QUIET_EVENT
    if (state or "open") != "open":
        return QUIET_CLOSED
    if wait_of(issue_labels) != WAIT_AYATO:
        return QUIET_NO_WAIT
    if event_name == "issue_comment":
        c = _flat(comment)
        # `type` を載せてこない経路でも落ちないように、login の `[bot]` も見る
        if c["type"] == "Bot" or c["login"].endswith("[bot]"):
            return QUIET_BOT
        if not _is_owner(c["login"]):
            return QUIET_NOT_OWNER
        if not signed_by_system(c["body"]):
            return QUIET_NOT_SIGNED
    return PING


def ping_history(issue, comments) -> list:
    """issue の**本文を先頭に置いた**書き込みの並び（古い順）。

    **本文も1本に数える。** 機械（`donor_calls` ほか）が本文に
    `@Ayato-kosaka` を入れて開いた issue は、開いた時点で鳴っている。
    コメントだけを見ると「まだ呼んでいない」に見えて、重ねて鳴らす。

    Args:
        issue: GitHub が返す issue（`user` と `body` を見る）。無ければ本文は数えない
        comments: その issue のコメント。**古い順**（GitHub が返す順）

    Returns:
        `{"login", "type", "body"}` の並び
    """
    out = []
    if issue:
        out.append(_flat(issue))
    for c in comments or []:
        out.append(_flat(c))
    return out


def already_called(history) -> bool:
    """**もう呼んであるか。** 重ねて鳴らさないための見分け。

    「最後に**あやとのアカウントで**書かれたものより後に、**通知の飛ぶ**
    メンションが在るか」で決める。

    - **通知が飛ぶのは、あやと以外が書いた生きたメンションだけ。**
      セッションも、あやと本人のトークンで書いている。GitHub は自分で自分を
      呼んでも通知を飛ばさないので、セッションが書いた `@Ayato-kosaka` は
      **字として在るのに1通も飛んでいない**（#306 の根）。だから数えない。
      囲い・引用・バッククォートの中のものも数えない（`mention_live()`）
    - **あやとのアカウントで書かれたら、前の呼び出しは使い終わり。**
      システムの新しい問いなら、その問いはまだ誰も呼んでいない。
      あやと本人の返事なら、前の呼び出しはもう読まれている。どちらも、
      そのあとに札が付けば**新しく呼ぶ**

    Args:
        history: `ping_history()` が作った並び（古い順）

    Returns:
        もう呼んであれば True
    """
    called = False
    for c in history or []:
        c = _flat(c)
        if _is_owner(c["login"]):
            called = False
        elif mention_live(c["body"]):
            called = True
    return called


def wait_ping_text() -> str:
    """鳴らすときのコメント。**中身は1行と署名だけ。**

    **issue の中身を1文字も入れない。** 題名にも本文にも視聴者さんの素性が
    在りうるし、鳴らす字は bot の書き込みとして残る。何を待っているかは
    すぐ上に書いてあるので、繰り返さない。

    `HANDLE` を行の先頭に置くのは、囲いや引用に巻き込まれないため。
    署名は `call_ayato.yml` と同じ（あやとから見て、呼んでいるのは
    いつも同じ相手）。
    """
    return (f"{HANDLE} 返事をお願いします（すぐ上の書き込みです）。\n"
            "\n---\n_あやと島案内鳥が呼んでいます_\n")


def wait_ping_verdict(event_name: str, action: str, label, issue_labels,
                      comment, history, state: str = "open") -> tuple:
    """**鳴らすか**と**鳴らす字**を決める。GitHub を触らない素の関数。

    1. 受け取りだけで決まるところ（`wait_ping_trigger()`）
    2. **重ねない**: もう呼んであれば鳴らさない（`already_called()`）。
       人が `call_ayato.yml` を回したあと・同じ issue に続けて書いたあと・
       機械が本文で呼んで開いた issue がこれに当たる

    Args:
        event_name, action, label, comment: `wait_ping_trigger()` と同じ
        issue_labels: その issue に**いま**付いている札（待ったあとに読み直したもの）
        history: `ping_history()` が作った並び（古い順）
        state: issue の**いまの**状態

    Returns:
        （答え, 鳴らす字）。鳴らさないときの字は空
    """
    v = wait_ping_trigger(event_name, action, label, issue_labels,
                          comment, state)
    if v != PING:
        return v, ""
    if already_called(history):
        return QUIET_ALREADY, ""
    return PING, wait_ping_text()


def ping_trigger_from_event(event_name: str, event) -> tuple:
    """受け取り一式から、**口を叩く前の**答えと相手を取り出す。

    Args:
        event_name: `$GITHUB_EVENT_NAME`
        event: `$GITHUB_EVENT_PATH` の中身

    Returns:
        （`wait_ping_trigger()` の答え, issue の番号）
    """
    ev = event or {}
    issue = ev.get("issue") or {}
    v = wait_ping_trigger(event_name, ev.get("action"), ev.get("label"),
                          issue.get("labels"), ev.get("comment"),
                          issue.get("state"))
    return v, issue.get("number")


def ping_from_event(event_name: str, event, issue, comments) -> tuple:
    """待ったあとに読み直した issue とコメントで、最後まで決める。

    **札と状態は読み直したほうを使う。** 待っているあいだに、あやとが
    答えて札が裏返る（`wait_flip`）・閉じられる、がありうる。受け取りに
    載っている札は、起きた瞬間のもの。

    Args:
        event_name: `$GITHUB_EVENT_NAME`
        event: `$GITHUB_EVENT_PATH` の中身
        issue: いま GitHub から読んだ issue（無ければ受け取りのものを使う）
        comments: いま GitHub から読んだコメント（古い順）

    Returns:
        （答え, 鳴らす字, issue の番号）
    """
    ev = event or {}
    now = issue or ev.get("issue") or {}
    v, text = wait_ping_verdict(event_name, ev.get("action"), ev.get("label"),
                                now.get("labels"), ev.get("comment"),
                                ping_history(now, comments), now.get("state"))
    return v, text, (now.get("number") or (ev.get("issue") or {}).get("number"))
