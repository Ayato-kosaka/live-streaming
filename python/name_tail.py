"""YouTube がハンドルの後ろに付ける**区別用のしっぽ**を見分ける。

    from name_tail import strip_tail
    strip_tail("@おにぎり-r9z")   → ("おにぎり", "r9z")
    strip_tail("@おにぎり1234")    → ("おにぎり", "1234")
    strip_tail("@おにぎり-chan")   → None   （しっぽではない。本人の字）
    strip_tail("@おにぎり2024")    → None   （西暦に見える）
    strip_tail("@たこ1234")        → None   （落とすと2字。短すぎる）

## なぜ要るのか

図鑑（`islandCharacter`）に入っているチャンネル名は**ハンドル**で、
引き当ては**完全一致**（`functions/src/islandCharacter.ts` の `findBy`、
`cards.ts` の `iconsOf`、`app/alertbox/matching.utils.ts`）。

ところが人が打つのは**ハンドルの人の部分だけ**で、しっぽまでは打たない。
「なまえ」と打っても `@なまえ1234` には当たらない。**当たらないと、
配信の画面にその人の絵が出ない。**

## しっぽの形は、当てずっぽうではなく数えて決めた

BigQuery `youtube_chat.chat_messages` の `author_name` は、ぜんぶ
ハンドル（`@…`）で入っている。**2,335通り**を 2026-09-17 に数えた。

| 末尾の形 | 件数 | 何か |
| --- | --- | --- |
| `-` ＋ 3字（英小文字と数字が**両方**混じる） | 638 | YouTube が付けた |
| `-` ＋ 5字（同上） | 132 | YouTube が付けた |
| `-` ＋ 3字（**英字だけ**） | 14 | `-chan` のような呼び方。**本人の字** |
| 数字ちょうど4桁 | 326 | YouTube が付けた（うち25件は西暦に見える） |
| 数字1〜3桁・5桁以上 | 267 | 本人の字が多い（1桁71・2桁88・3桁87とばらける） |

**効いている手がかりは3つ。**

1. **長さが3と5に集中する**（3字 660 / 4字 16 / 5字 140）。
   人が付ける字なら、この谷はできない
2. **英字と数字が混じる**（3字のうち 638/660）。英字だけのものは
   `-chan` のような**呼び方**で、落とすと名前が変わる
3. **数字はちょうど4桁に山がある**（1桁71・2桁88・3桁87に対して**4桁326**）。
   人が付ける数字なら、1桁2桁のほうが多いはず

だから落とすのは**この3つの形だけ**にして、あとは触らない。
**迷ったら落とさない。** 落とし足りないぶんは後から足せるが、
落としすぎて別人に当たると、**配信中に人違いの絵が出る**（その場では直せない）。

## 西暦に見える4桁は落とさない

`1900`〜`2030` は、生まれ年や始めた年を自分で付けた可能性がある
（実測で 326件中 25件）。**25件を取り逃がすほうを選ぶ。**

## 落としたあとが短すぎるものは、使わない

実測で、しっぽ付き 1,096件のうち**281件は残りが4字未満**になる
（うち151件は2字未満）。「あお」のような2〜3字は、**別の誰かの
名乗りと普通にかぶる。** 図鑑の口も「2人に当たったら決めない」で
通してあるので（`islandCharacter.ts` の `findBy` が `limit(2)`）、
ここでも短いものは**作らない**ことにした。

**この 4 は測って出た数ではなく、こちらの判断。** 下げたくなったら、
下げた形でどれだけぶつかるかを数えてから下げる。
"""

import re

# `-` ＋ 3字 か 5字。**英小文字と数字が両方混じるものだけ。**
# 英字だけ（`-chan`）も数字だけ（`-123`）も、ここでは落とさない
_HYPHEN = re.compile(r"-([a-z0-9]{3}|[a-z0-9]{5})$")

# 数字ちょうど4桁。**その手前が数字でないこと**を見る
# （5桁以上を「後ろ4桁」として切らないため）
_DIGITS4 = re.compile(r"(?<![0-9])([0-9]{4})$")

# 西暦に見える4桁は落とさない
YEAR_MIN, YEAR_MAX = 1900, 2030

# 落としたあとの長さの下限（符号位置）。**測って出た数ではなく判断**
MIN_BASE = 4


def _mixed(tail: str) -> bool:
    """英小文字と数字が**両方**入っているか。"""
    return any(c.isdigit() for c in tail) and any(c.isalpha() for c in tail)


def strip_tail(name):
    """しっぽを落とした形を返す。しっぽが無ければ None。

    先頭の `@` は落として返す（人が打つのは `@` 無しのほうで、
    `keysOf` は `@` 付きから `@` 無しを作るが、逆は作らない）。

    Args:
        name: チャンネル名（ハンドル）。`@` は付いていても付いていなくてもよい

    Returns:
        (しっぽを落とした字, しっぽの中身)。落とすものが無ければ None
    """
    if not isinstance(name, str):
        return None
    body = name.strip().lstrip("@")
    if not body:
        return None

    m = _HYPHEN.search(body)
    if m and _mixed(m.group(1)):
        base = body[: m.start()]
    else:
        m = _DIGITS4.search(body)
        if not m:
            return None
        if YEAR_MIN <= int(m.group(1)) <= YEAR_MAX:
            # 西暦に見える。自分で付けた数字かもしれない
            return None
        base = body[: m.start()]

    base = base.strip()
    # 末尾に残った区切り（`@なまえ-1234` の `-`）は落とす。
    # 落とさないと「なまえ-」という、誰も打たない字ができる
    base = base.rstrip("-_.")
    if len(base) < MIN_BASE:
        return None
    return base, m.group(1)
