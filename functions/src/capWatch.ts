/**
 * **数えるために開けた窓が埋まったら、鳴らす。**
 *
 * Firestore の `.limit(N)` は、N 件を超えた日に**黙って N 件で返す。**
 * 返した側は「これで全部」の顔をするので、呼んだ画面も、見ている人も、
 * 切れたことに気づけない。実際に起きている:
 *
 *   - `/cards` を新しい順600枚で切っていて、本番617枚のうち**いちばん古い
 *     17枚が公開の口から取れていなかった**（`docs/island-api.md` 3章）
 *   - 付箋を数える窓（`WAITING_SCAN`）が300枚で、机の札が**本当の数より
 *     小さい数を言い続けていた**
 *
 * どちらも、**窓を広げたこと**ではなく**鳴るようにしたこと**で見つかる形に
 * なった。窓はいつか必ずまた埋まるので、広げるだけでは同じ日が来る。
 *
 * ## `warn` ではなく `error`
 *
 * ここに来た時点で、**送り（ページング）を入れる直しが要る。**
 * 広げて凌ぐと、次に埋まる日は中身がもっと大きくなっている
 * （`cards.ts` の `CARDS_HARD_CAP` の注と同じ決め）。
 *
 * ## `>=` で見る
 *
 * `.limit(N)` に対して「ちょうど N 件あった」と「N 件より多い」は
 * **区別できない。** 区別したければ `N + 1` を引いて `> N` で見る
 * （`cards.ts` がそうしている）。引き直せない場所——`N` が応答の件数
 * そのものになっている場所——では、ちょうどのときも鳴らすほうに倒す。
 * **鳴らしすぎて困るのは人の手間だけで、鳴らさずに切れるのは数が狂う。**
 *
 * ## 素性を1文字も出さない
 *
 * このリポジトリは公開で、Actions のログも誰でも読める。出すのは
 * **どの窓か・いくつで切ったか**だけ。鍵も名前も件の中身も渡さない。
 */

import {logger} from "firebase-functions";

/**
 * 窓が埋まっていたら `logger.error` を出す。
 *
 * @param {string} what どの窓か。**定数の名前と、引いた場所**を書く。
 *   人の名前・チャンネル・書類の中身は入れない
 * @param {number} size 引けた件数（`snap.size`）
 * @param {number} cap 窓の大きさ（`.limit()` に渡した数）
 * @return {boolean} 埋まっていたか。呼ぶ側が応答に印を足したいときに使う
 */
export function capHit(what: string, size: number, cap: number): boolean {
  if (size < cap) return false;
  logger.error(
    `窓が埋まりました: ${what}（${cap}件で切っています）。` +
      "ここから先は数にも一覧にも入っていません。" +
      "窓を広げるのではなく、送り（ページング）を入れてください",
  );
  return true;
}
