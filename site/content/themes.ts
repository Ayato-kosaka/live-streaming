/**
 * いま**書ける**宛先か。読む側は関係ない（棚には全部並ぶ）。
 *
 * あやとの指摘（2026-09-30）:
 *
 * > 付箋の項目に古いのが多くて醜い
 *
 * 実際、13ある宛先のうち**12が終わった話**だった（北欧の旅は 9/21 に終わり、
 * 企画3つも全部済んでいる）。生きている宛先1つが、死んだ札12枚の上に乗っていた。
 *
 * 判定の出どころは2つある。**どちらも「字で持たない」ほうを選んでいる。**
 *
 *   1. 旅の宛先 … `closed`（こちらが畳んだ印）
 *   2. 企画の宛先 … **同じ id の企画に日付を聞く**（`groupOf` と同じ）。
 *      字で「終わった」と持つと、`/next` が「もう行ってきた」に置いたものが
 *      掲示板ではまだ書けたままになる
 */
export function isOpenTheme(t: Theme, now: Date | null): boolean {
  if (t.closed) return false;
  return groupOf(t, now) !== PLAN_DONE_GROUP;
}

/** いま書ける宛先だけ。**書く欄の選び先は、これを使う。** */
export const openThemes = (now: Date | null): Theme[] =>
  THEMES.filter((t) => isOpenTheme(t, now));

/**
 * **宛先を決め打ちしている面で、その宛先がもう締め切られているか。**
 *
 * 2026-10-11 まで、畳んだ宛先を決め打ちしている面に**書く窓が残っていた。**
 * 畳みの判定（`isOpenTheme`）を見ていたのは掲示板の選び札だけで、
 * 面が宛先を決め打ちしている側（`components/live/Notes.tsx` の `fixed`）は
 * 1度も見ていなかった。だから `/nordic/finland` の「フィンランドで
 * これやって」に、締め切ったあとも貼れた。
 *
 * **赤くならない形の壊れ方。** 窓は出るし、貼れば 200 で入る
 * （サーバーは宛先の表を持っていないので、締め切りを知らない）。
 * 入った先の棚は畳みの中なので、書いた人からは消えたように見える。
 *
 * 画面の側で `t.closed` を直に見ないのは、**企画あての締め切りが
 * 字ではなく日付で決まる**から（`isOpenTheme`）。判定を2か所に書くと、
 * 片方だけが日付を見る形になる。
 *
 * @param fixed 面が決め打ちしている宛先。選ばせる面（掲示板）は undefined
 * @param now 画面が出てからの今。まだ分からないときは null
 * @return 締め切られているか。決め打ちしていない面はいつも false
 */
export const shutDest = (fixed: Theme | undefined, now: Date | null): boolean =>
  !!fixed && !isOpenTheme(fixed, now);

/** id から1つ引く。知らない id は undefined。 */
export const themeById = (id: string): Theme | undefined =>
  THEMES.find((t) => t.id === id);

/** 札の一行ぶん。見出しと、そこに並ぶ宛先。 */
export type Shelf = { group: string; themes: Theme[] };

/**
 * 見出しの並び。**ここに書いた順に出る。読む側と書く側の両方。**
 *
 * ## なぜ1つの表なのか（2026-10-11）
 *
 * 前はこの表に**畳んだ見出しだけ**が並んでいて、グッズ（`GOODS_GROUP`）と
 * 「そのほか」（`OTHER_GROUP`）は載っていなかった。畳む日が来ない見出しなので
 * 要らない、という理屈だったが、**書く側（`writeShelves`）を束ねた日に
 * そこが穴になる**——表に無い見出しは `rank` が後ろへ回すので、
 * 札は出るが**並びがこちらの決めたものでなくなる。**
 *
 * 赤くならない。並びが変わるだけ。だから表を1つにして、
 * **出てきうる見出しを全部ここに並べる。**
 * 並んでいない見出しが1つでもあれば `selftest/themes_selftest.mjs` が落ちる。
 *
 * ## 並びの理由
 *
 * - **いちばん上は、いま注文を受け付けている先**（＝次に行く旅）。
 *   いま居る国ではない（`THEMES` の頭の注）
 * - 終わった旅は、その下に古い順で
 * - 「行ってきた企画」は、これからのものより下。終わったものが上に来ると、
 *   次に何があるのかを探すのに、済んだものを読み飛ばすことになる
 * - グッズは旅でも企画でもないので、旅と企画のあと
 * - 「そのほか」は**どこにも入らない字の受け皿**なので、いつも最後
 *
 * 書く側に出るのは、いま書ける宛先が在る見出しだけ。畳んだ見出し
 * （アルバニア・北欧・行ってきた企画）は空になるので、この1つの表でも
 * 書く側の並びは「北マケドニアの旅 → グッズ → そのほか」になる。
 */
const ORDER = [
  MACEDONIA_GROUP,
  ALBANIA_GROUP,
  NORDIC_GROUP,
  PLAN_GROUP,
  PLAN_DONE_GROUP,
  GOODS_GROUP,
  OTHER_GROUP,
];

/** 並びの表。**見張り（`selftest/themes_selftest.mjs`）がここを読む。** */
export const GROUP_ORDER: readonly string[] = ORDER;

/**
 * 宛先の札を、見出しごとに束ねる。
 *
 * **`now` は画面が出てから渡す。** `output: "export"` なので、ここで
 * `new Date()` を呼ぶとビルドした日が焼き込まれる（`CLAUDE.md`）。
 * 渡すまでは**焼いた日**（`BUILT_AT`）で仕分ける。分からないからと
 * 「全部これから」にすると、**終わった企画がいつまでも棚に居座る。**
 * 焼いた日なら、古くなるのは焼いてから終わった企画だけで、
 * しかも画面が出た時点で本物の今日に直る。
 *
 * @param list 並べる宛先
 * @param now 画面が出てからの今。まだ分からないときは null
 */
export function shelves(list: Theme[], now: Date | null): Shelf[] {
  const out: Shelf[] = [];
  for (const t of list) {
    const g = groupOf(t, now);
    const shelf = out.find((s) => s.group === g);
    if (shelf) shelf.themes.push(t);
    else out.push({ group: g, themes: [t] });
  }
  /* 見出しの並びは `ORDER`。表に出てこない見出し（「そのほか」）は、
     `THEMES` に出てきた順のまま後ろへ回す。 */
  return out.sort((a, b) => rank(a.group) - rank(b.group));
}

const rank = (g: string) => {
  const i = ORDER.indexOf(g);
  return i < 0 ? ORDER.length : i;
};

/**
 * **書く先の選び札を、見出しごとに束ねる。**
 *
 * あやとの言葉（2026-10-11）:
 *
 * > 以下はグッズとしてカテゴリ分けして欲しい
 * > （カテゴリわけ機能なかったっけ？なかったらいいや）
 *
 * **仕掛けは在った。** 畳みのほう（`shelves`）が前から見出しで束ねていて、
 * 束ねていなかったのは**書く先の選び札（「どこへ」）だけ**だった。
 * 同じ仕掛けを同じ表（`ORDER`）で通す。
 *
 * **並びを画面（`components/live/Notes.tsx`）に書かない。** 書くと、
 * 読む側と書く側で並びの出どころが2つになって、片方だけ古くなる
 * （`docs/island-standards.md` 8章）。
 *
 * 中身は `shelves` と同じなので、関数を分けてあるのは**呼ぶ側の読みやすさ**と、
 * 「書く側にも並びの決めが要る」ことを型で言うため。
 *
 * @param list 書ける宛先（`openThemes`）
 * @param now 画面が出てからの今。まだ分からないときは null
 */
export const writeShelves = (list: Theme[], now: Date | null): Shelf[] =>
  shelves(list, now);

/**
 * その宛先が、いまどの見出しの下にいるか。
 *
 * 企画あて（`PLAN_GROUP`）だけ、同じ id の企画に日付を聞く。
 * **`planPhase` に合わせる。** `/next` が「もう行ってきた」に置いたものが
 * 掲示板では「これから」に並ぶ、という食い違いを作らないため。
 */
function groupOf(t: Theme, now: Date | null): string {
  if (t.group !== PLAN_GROUP) return t.group;
  const p = planById(t.id);
  if (!p) return t.group;
  /* 画面が出る前は、**焼いた日**で仕分ける（`content/plans.ts` の `BUILT_AT`）。
     ここを「分からないから、これから」にしていたので、9月6日に終わった
     フード＆ワイン祭りが、9月10日に配られた HTML でも
     「これからの企画」の棚に並んでいた（あやと 2026-09-10）。 */
  return planPhase(p, now ?? BUILT_AT) === "after" ? PLAN_DONE_GROUP : PLAN_GROUP;
}
