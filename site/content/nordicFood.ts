/** 国の日本語名。`nordic/index.json` から引く（名簿を手で作らない）。 */
const NAMES = new Map(INDEX.countries.map((c) => [c.slug, c.name]));

/** 国ごとの色。見出しの帯に使う。 */
const COLORS = new Map(INDEX.countries.map((c) => [c.slug, c.color]));

export function foodCountryName(slug: string): string {
  return NAMES.get(slug) ?? "";
}

export function foodCountryColor(slug: string): string | undefined {
  return COLORS.get(slug);
}

/** その国のぶんを、書いてある順で返す。 */
export function foodsOf(slug: string): DailyFood[] {
  return DAILY_FOODS.filter((f) => f.country === slug);
}
