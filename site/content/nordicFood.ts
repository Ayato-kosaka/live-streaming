/**
 * 北欧・バルトの「ふだんのごはん」。
 *
 * **観光名物ではない。** `content/nordic/*.json` の `cat: "eat"` は、市場ホールや
 * 老舗カフェやプリンセスケーキで、あれは「その街へ行ったら寄る店」の軸。
 * ここはまったく別の軸で、選ぶ条件は次の4つ。どれかではなく、なるべく全部。
 *
 *   - 現地の人が子どもの頃から食べている
 *   - スーパーの棚か、家の冷蔵庫にふつうにある
 *   - 季節になると、何もしなくても食卓に出てくる
 *   - その国だけの食べ方がある
 *
 * だから surströmming ではなく knäckebröd、トナカイではなく ruisleipä を選ぶ。
 * 店の名前は出さない。**棚と食卓の話しかしない。**
 *
 * ## `ask` がこの企画の芯 — **当てにいく問いではなく、教わる問い**
 *
 * よりどころは、あやとが今日くれた一行。
 *
 * > 今回のテーマが、人との交流(ヒッチハイク)、食べる、見る
 *
 * **人との交流＝ヒッチハイク。** 乗せてくれた人と車の中で黙っていても始まらないので、
 * **食べものの話を、口を開くきっかけにする。**
 * こちらが正解を持っていて当てにいく形（「これ好き？」「合ってる？」）だと、
 * 相手はうなずくだけで終わる。**相手が教える側に回る問い**にする。
 *
 * だから `ask` は、次の3つを満たす形にしてある。
 *
 *   1. **相手が主役になる。** 答えるとその人が詳しい人になる問いにする。
 *      はい／いいえで終わる形は置かない
 *   2. **短い。** 走っている車の中で、言葉の通じない相手と交わす一言なので、
 *      現地語は**10語以内**を目安にした。実際いちばん長いもので5語
 *   3. **1品に1つ、違う角度。** 同じ国の中で同じ聞き方を2度しない
 *      （何をのせる／何と食べる／どう作る／どこで買う／どこで採れる／
 *      いつ食べる／誰が作る／どれがいちばん）。40回同じ会話にならないように
 *
 * 角度のうち「作り方を教えて」は、どの国にも1つずつ置いた（ジュレク・
 * ケプタドゥオナ・灰色の豆・カマ・プーロ・ファールコルヴ）。
 * 話がいちばん長く続く聞き方だから、というだけの理由。
 *
 * **ダンボールやホワイトボードを前提にした書き方はしていない。**
 * 2026-08-17 の会議にはその案が出ているが、2週間後（09-05）には1回も出てこない。
 * 生きているのか消えたのかチャットからは分からないので、**画面にも、ここの
 * 決めごとにも、その企画がある前提を置かない**（`docs/island-meeting-nordic.md`
 * 「いま生きている決めごと」）。
 *
 * ## 国は6つだけ
 *
 * 旅程（`content/nordic.ts` の `ROUTE` `DAYS`）で実際に足を置く国に合わせてある。
 * 既存の `content/nordic/*.json` は行かない街（ヨーテボリ・マルメ・ロヴァニエミ）
 * まで持っているが、ここは**通る国だけ**。
 * 国の名前と色は持たない。`content/nordic/index.json` から引く
 * （名簿を手で作らない。`docs/island-misses.md` 決めごと3）。
 *
 * ## 季節は 2026-09-11〜09-27 に合わせてある
 *
 * 旅は9月なかばから下旬。**その時期に出ないものを「季節になると出る」と書かない。**
 * ザリガニは8月のもので、9月下旬にはもう名残。そう書いてある。
 *
 * ## 数字について
 *
 * `price` は 2026年9月にスーパーの値段を1つずつ確かめられたものにだけ付けた。
 * 確かめられなかった品には付けていない（`docs/island-standards.md`「数字は
 * 意味のあるものだけ」）。円は €1≈180円 / 1zł≈41円 / 1kr≈16円 の目安。
 * **値段は動く。目安として読む。**
 */

