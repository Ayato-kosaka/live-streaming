/**
 * 「いま」の初期値。/island-api/state の current で上書きされる。
 *
 * ## ここに地名を焼かない
 *
 * 旅は毎日動くので、**ここに書いた地名は必ずいつか嘘になる。**
 * 焼いてあったのは「ジョージア・トビリシ」（2026-09-04 にあやとが打った字）で、
 * ふだんは口が返るまでの数百ミリ秒しか出ない。**でも口が返らない日は、
 * それが1日出しっぱなしになる。** 旅のあいだは電波の細いところを通るので、
 * 返らない日は必ず来る。しかも打ち直せるのは本人だけで、旅のあいだ本人は
 * 走っている車の中にいる。
 *
 * **「古い答えを出す」より「まだ分からない、と言う」ほうが正しい。**
 * だからここに置くのは、**いつ読んでも本当のことだけ**にする。
 *
 * 「いまどこ」は3段で決まる（判定と言い方は `lib/stay.ts` の `placeWord`）。
 *
 *   1. あやとが打った字（`/island-api/state` の current.place）… 街まで分かる
 *   2. いま歩いている旅（`travelNow`）… 「北欧周遊のとちゅう」。**通信が要らない**
 *   3. ここ … どちらも無い日
 *
 * 3 に地名を置くと、1 も 2 も出せない日にその地名が「いま」として出る。
 * だから 3 は **場所を名指ししない**。サイトがいつでも言い切れるのは
 * 「世界のどこかにいる」ところまでで、それ以上は分からない。
 *
 * **空にはしない。** 空にすると「しばらく空っぽ→急に出る」になるうえ、
 * この字は文の中にも埋まる（島のカモメの「いまは◯◯だよ」、島の板の
 * 「◯◯から繋いでます」、表紙の「いま ◯◯」）ので、空だと文が壊れる。
 * どの文に入れても読めて、どの日に読んでも本当、という字を1つ置く。
 */
