/**
 * 歩いた国の数を差し込む印。**焼いた HTML に数を入れないため。**
 *
 * セリフはこのファイルを読み込んだ時点で1本の文字列になるので、数をそのまま
 * 差し込むと**焼いた日の数**が固まる。印だけ置いて、話しかけられたときに
 * `linesOf` が替える（`content/nights.ts` の `say` と同じ形）。
 */
export const WALKED = "\u00a7w";

/** 印を、いまの数に替える。印が無ければそのまま返す。 */
export const walkedSaid = (t: string, now: Date = new Date()): string =>
  t.includes(WALKED) ? t.split(WALKED).join(String(countriesWalked(now))) : t;

/**
 * 行き先の名前を差し込む印。**旅の名前をセリフに焼き込まないため。**
 *
 * 前はここが「北欧」と直書きで、76人×3本＝228本に入っていた。旅は終わって
 * 次の行き先へ移るので、**書いた日の行き先が全員の口に残り続ける。**
 * 北欧旅が終わった翌日から、島じゅうが「北欧まで行ったんやで」と言い続けた。
 *
 * 印だけ置いて、話しかけられたときに `linesOf` が替える（`WALKED` と同じ形）。
 * 替える先は `chapters.ts` の章で、**日どりの表はこちらに持たない。**
 */
const DEST = "§t";

export type Voice = {
  /** 住人の見分け（キャラクター画像の Drive ID）。RESIDENTS と同じもの。 */
  icon: string;
  /** 話し方のメモ。セリフを足すときの指針。 */
  note: string;
  /**
   * 1言目。その日はじめて島の誰かに話しかけたときだけ、これが出る。
   * 2言目からは lines に戻る。挨拶で終わらせず、役に立つことを1つ入れる。
   */
  greet: { first: string; back: string };
  /**
   * 配信の時間を言うひとこと。**旅のあいだは言い方が変わるので2つ書く**
   * （`[いつもの, 旅のあいだの]`）。
   *
   * ふつうのセリフと分けてあるのは、住んでる人の面（`/friends`）が上の2つを
   * 焼いて出すから。時間のことを `lines` に混ぜておくと、旅に出た日から
   * 17日ぶん「毎晩22時」と焼かれたまま出る。
   *
   * 旅のあいだの言い方は `content/nights.ts` と揃える。時刻は言わない。
   */
  hours: [string, string];
  /**
   * 旅のことを言うひとこと。**出る前・道の上・帰ってから の3つを書く**
   * （`[出る前, 旅のあいだ, 帰ってから]`）。
   *
   * `lines` から分けてあるのは、**ここだけが時点で本当かどうかが変わる**から。
   * 混ぜておくと、出発した翌日から「北欧までヒッチハイクやて」「楽しみだね」と、
   * 22人が17日間ずっと、もう始まっている旅を先の話として喋る。
   * 帰ってきたあとも同じ字のままなので、そこから先はずっと嘘になる。
   *
   * 3つに分ける理由は、`hours` の2つでは足りないから。あちらの切り替えは
   * 「時刻を言えない期間か」の1つだけで、**出る前と帰ってからが同じ側に入る。**
   * 旅の話は、その2つでまったく逆のことを言う。
   *
   * 書くときは `lines` と同じ決まりごと。**日付も距離も書かない**（上の 7）。
   *
   * **行き先の名前を書かない。`${DEST}` を差し込む**（上の 7 と同じ理由）。
   * ここは1本ずつ手で書くところなので、名前を埋めると**旅が変わるたびに
   * 76人×3本を書き直す**ことになり、書き直せなかったぶんがそのまま嘘になる。
   * 実際そうなっていて、北欧が終わっても全員が「北欧まで行った」と言っていた。
   *
   * **行き方を書かない。** 「ヒッチハイクで」「陸路ぜんぶ」は北欧旅の中身で、
   * 次の旅では嘘になる。**どう行くかが決まっていない旅もある**（アルバニアは
   * 行き先だけが決まっていて、回り方も日どりもこれから）。
   * 書いてよいのは、どの旅で読んでも本当のこと——行き先と、その人の反応だけ。
   */
  trip: [string, string, string];
  lines: string[];
};

/**
 * **いま住人が話している旅**と、その時点。`0=出る前 / 1=道の上 / 2=帰ってから`。
 *
 * **「旅の章」を配列の先頭から1つ選ばない。** 前はここが「`CHAPTERS` を頭から
 * 探して、始まる時刻の決まっていない章を1つ取る」書き方で、
 * **いちばん先に書いてある旅**を見ていた。章は増えるほうへ足していくので、
 * 次の旅に印を立てても、終わった北欧がいつまでも勝つ。
 * **旅が変わった日に、誰も気づかないまま判定だけが前の旅に残る。**
 *
 * 日どりは1つも持たない。`chapters.ts` がすでに全部答えを持っている——
 * いまどの島にいるかは `chapterNow`、その旅がまだ続いているかは
 * `chapterRunning`、これから行く島は `chapterNext`。
 *
 * 時点の決め方:
 *
 *   1. いまいる島の旅が、まだ続いている → **道の上**（行き先はその島）
 *   2. 続いていない。次の旅が待っている   → **出る前**（行き先はその島）
 *   3. どちらでもない                     → **帰ってから**（行き先は最後の島）
 *
 * **1 を `looseStart`（始まる時刻が決まっていない章）で見ない。** それは
 * 「配信の時刻を言えない期間か」の印で、**旅をしているかの印ではない**
 * （`hours` の切り替えがそれ）。回り方が決まっていない旅——アルバニアは
 * 行き先だけが決まっていて、ヒッチハイクかどうかも未定——には印が立たないので、
 * `looseStart` で見ると**着いた日から「帰ってきた」と言い出す。**
 * 続いているかどうかは `chapterRunning` がすでに1つだけ持っている。
 *
 * **画面が出てから呼ぶこと。** 静的書き出しなので、焼くと出発の日から
 * 旅のあいだずっと「出る前」のままになる（`chapters.ts` の `looseStartNow` と同じ）。
 */
function tripNow(now: Date): { to: Chapter; phase: 0 | 1 | 2 } {
  const here = chapterNow(now);
  if (chapterRunning(here, now)) return { to: here, phase: 1 };
  const next = chapterNext(now);
  if (next) return { to: next, phase: 0 };
  return { to: here, phase: 2 };
}

/**
 * 章の名前を、口で呼ぶ形にする。
 *
 * 章の名前は島の名前でもあるので「北欧周遊」のように**旅の形**が付く。
 * セリフの中では「北欧まで行ったんやて」と言うので、語尾の「周遊」だけ落とす。
 * **別名の表をここに作らない**——表を持つと、章を足した日に片方だけ古くなる。
 */
const destName = (c: Chapter): string => c.name.replace(/周遊$/, "");

/** 印を、いま住人が話している旅の行き先に替える。印が無ければそのまま返す。 */
const destSaid = (t: string, now: Date = new Date()): string =>
  t.includes(DEST) ? t.split(DEST).join(destName(tripNow(now).to)) : t;

