/**
 * 島の住人が話すこと。
 *
 * 島にいるのは視聴者さんご本人（自分で作ったキャラクターがそのまま住んでいる）。
 * だから **口調はその人のものを写す**。BigQuery の youtube_chat.chat_messages を読んで、
 * その人らしい言い回し・語尾・テンションを取ってある。
 *
 * ただし **中身は配信のコメントの丸写しにしない**（`docs/island-design.md`）。
 * 文脈のないコメントは、初めて島に来た人には意味が通らない。
 *
 *   だめな例: 「油はコロッケの半分の高さね。少ないなら焼きコロッケ風にすれば安心だよー」
 *   よい例:  「初めてならね、いまのポストを見てみて。いまどこにいるか書いてあるよー」
 *
 * 書くときの決まりごと:
 *   1. 口調はその人のもの。似ていないセリフは、いない人が喋っているのと同じ。
 *   2. 中身は「初めて来た人の役に立つこと」だけ。島の案内か、あやとの事実。
 *   3. 1文で完結させる。吹き出しは画面の上に1つ出るだけなので、長いと読まれない。
 *   4. 本人の代弁はしない。事実はサイトに載っている範囲だけ。
 *   5. 名前は出さない。誰が喋っているかは、その人のキャラクターだけが示す。
 */

