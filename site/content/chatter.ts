const BY_ICON = new Map(VOICES.map((v) => [v.icon, v]));

/**
 * その住人のセリフ帳。まだ書いていない人は共通のひとこと。
 *
 * 配信の時間のひとことと、旅のひとことは、**話しかけられたときに選ぶ**。
 * どちらも時点で言い方が変わるので、焼き込むと出発の日から17日ぶん
 * 古いことを言う（`content/nights.ts`、上の `tripPhase`）。
 */
export const linesOf = (icon?: string, now: Date = new Date()): string[] => {
  const v = icon ? BY_ICON.get(icon) : undefined;
  const hours = v?.hours ?? COMMON_HOURS;
  const trip = v?.trip ?? COMMON_TRIP;
  return [
    hours[looseStartNow(now) ? 1 : 0],
    trip[tripNow(now).phase],
    ...(v?.lines ?? COMMON_LINES),
  ].map((t) => destSaid(walkedSaid(t, now), now));
};

/**
 * その住人の1言目。
 * @param {string | undefined} icon 住人の見分け
 * @param {"first" | "back"} kind はじめての人か、しばらく空いた人か
 */
export const greetOf = (icon: string | undefined, kind: "first" | "back"): string =>
  ((icon && BY_ICON.get(icon)?.greet) || COMMON_GREET)[kind];

/** セリフを書いてある住人かどうか。話しかけられる印を出す人を選ぶのに使う。 */
export const hasVoice = (icon?: string): boolean => !!icon && BY_ICON.has(icon);
