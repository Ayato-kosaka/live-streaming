/**
 * 島の住人が話すこと。
 *
 * 島にいるのは視聴者さんご本人（自分で作ったキャラクターがそのまま住んでいる）。
 * だから **口調はその人のものを写す**。BigQuery の youtube_chat.chat_messages を読んで、
 * その人らしい言い回し・語尾・テンションを取ってある。
 *
 * ただし **中身は配信のコメントの丸写しにしない**（`docs/island-design.md`）。
 * 文脈のないコメントは、初めて島に来た人には意味が通らない。
 *
 *   だめな例: 「油はコロッケの半分の高さね。少ないなら焼きコロッケ風にすれば安心だよー」
 *   よい例:  「初めてならね、『いまどこ』を見てみて。いまいる場所が書いてあるよー」
 *
 * 書くときの決まりごと:
 *   1. 口調はその人のもの。似ていないセリフは、いない人が喋っているのと同じ。
 *   2. 中身は「初めて来た人の役に立つこと」だけ。島の案内か、あやとの事実。
 *   3. 1文で完結させる。吹き出しは画面の上に1つ出るだけなので、長いと読まれない。
 *   4. 本人の代弁はしない。事実はサイトに載っている範囲だけ。
 *   5. 名前は出さない。誰が喋っているかは、その人のキャラクターだけが示す。
 *   6. 絵文字は書かない。誰が誰かの目印は、下のコメントの Unicode 番号で示す
 *      （`content/residents.ts` の emoji と同じもの）。
 *   7. **まだ動く数を書かない。** ここに書いた数は、その数を持っている面から
 *      独立して古くなる。6人が「北欧まで 1,542km」と喋っていて、`/nordic` が
 *      旅程から出している 1,377km（`HITCH_KM`）と 165km ちがっていた——旅程は
 *      出発の日まで直され続けるので、手で書いた側だけが置いていかれる。
 *      導出を読みに行くと旅程の表 54KB が島の吹き出しに付いてくるので、
 *      **行き先と手段だけを言って、数はその面に任せる**（`docs/island-misses.md` #38）。
 *      済んだ旅の数（イランまで 380km）は動かないので、そのままでよい。
 *
 * 事実として書いてよいこと（サイトに載っている範囲。**建物の取り違えに注意**）:
 *   あやとのこと = あやとがどんな人か / 配信 = 配信の型5つ /
 *   作った料理 = 料理のスタンプ帳（**料理は「配信」の面ではない**） /
 *   アプリ = グルメアプリ / 歩いた国 = 歩いた17カ国 /
 *   伝説の企画 = 語りつがれている企画8つ / 企画をだす = 誰でも出せる /
 *   これから = 次の企画 / いまどこ = いまいる場所
 *
 * 島の入口の名前は**中身をそのまま言う名前**にしてある（たき火広場・旅の桟橋を
 * やめた理由）。セリフの中では鉤括弧で囲む。囲まないと、
 * 「作った料理が並んでる」が場所の名前なのか物なのか読み分けられない。
 *
 * 口調を確かめるとき（BigQuery。`docs/island-db.md`）:
 *
 *   -- よく来てくれている人と、その人らしい書き込み
 *   WITH top AS (
 *     SELECT author_channel_id, ANY_VALUE(author_name) nm,
 *            COUNT(DISTINCT DATE(published_at,'Asia/Tokyo')) d
 *     FROM `live-streaming-d3cac.youtube_chat.chat_messages`
 *     WHERE published_at >= TIMESTAMP_SUB(CURRENT_TIMESTAMP(), INTERVAL 90 DAY)
 *       AND author_name != '@あやとグルメアプリ'
 *     GROUP BY 1 ORDER BY d DESC LIMIT 24)
 *   SELECT t.nm, t.d, c.message_text
 *   FROM top t JOIN `live-streaming-d3cac.youtube_chat.chat_messages` c
 *     USING (author_channel_id)
 *   WHERE LENGTH(c.message_text) BETWEEN 8 AND 80
 *
 * **キャラクター画像と YouTube のチャンネルを結ぶ表は、どこにも無い。**
 * だから確かめられるのは「この話し方の人が本当にいるか」までで、
 * 「この絵の人がこの話し方か」は確かめられない。結ぶ表を作るなら
 * チャンネルIDは配信側に置く。サイトに焼くと、名前を出していない人の
 * 身元が出てしまう（`docs/island-concept.md` 6章）。
 *
 * 1言目だけは `greet` に分ける（`docs/island-play.md` 仕掛け6）。
 * はじめての人には「はじめまして」、しばらく空いた人には「久しぶり」。
 * **空けた日数は数えない。来なかった日を責める道具にしない。**
 * 「久しぶり」は歓迎であって督促ではないので、必ず役に立つことを1つ添える。
 */

import { CHAPTERS, chapterSpan, looseStartNow } from "./chapters";

export type Voice = {
  /** 住人の見分け（キャラクター画像の Drive ID）。RESIDENTS と同じもの。 */
  icon: string;
  /** 話し方のメモ。セリフを足すときの指針。 */
  note: string;
  /**
   * 1言目。その日はじめて島の誰かに話しかけたときだけ、これが出る。
   * 2言目からは lines に戻る。挨拶で終わらせず、役に立つことを1つ入れる。
   */
  greet: { first: string; back: string };
  /**
   * 配信の時間を言うひとこと。**旅のあいだは言い方が変わるので2つ書く**
   * （`[いつもの, 旅のあいだの]`）。
   *
   * ふつうのセリフと分けてあるのは、住んでる人の面（`/friends`）が上の2つを
   * 焼いて出すから。時間のことを `lines` に混ぜておくと、旅に出た日から
   * 17日ぶん「毎晩22時」と焼かれたまま出る。
   *
   * 旅のあいだの言い方は `content/nights.ts` と揃える。時刻は言わない。
   */
  hours: [string, string];
  /**
   * 旅のことを言うひとこと。**出る前・道の上・帰ってから の3つを書く**
   * （`[出る前, 旅のあいだ, 帰ってから]`）。
   *
   * `lines` から分けてあるのは、**ここだけが時点で本当かどうかが変わる**から。
   * 混ぜておくと、出発した翌日から「北欧までヒッチハイクやて」「楽しみだね」と、
   * 22人が17日間ずっと、もう始まっている旅を先の話として喋る。
   * 帰ってきたあとも同じ字のままなので、そこから先はずっと嘘になる。
   *
   * 3つに分ける理由は、`hours` の2つでは足りないから。あちらの切り替えは
   * 「時刻を言えない期間か」の1つだけで、**出る前と帰ってからが同じ側に入る。**
   * 旅の話は、その2つでまったく逆のことを言う。
   *
   * 書くときは `lines` と同じ決まりごと。**日付も距離も書かない**（上の 7）。
   */
  trip: [string, string, string];
  lines: string[];
};

/** 旅の章（＝始まる時刻の決まっていない章）。**期間の定数をここに作らない。** */
const TRIP_CHAPTER = CHAPTERS.find((c) => c.looseStart);

/**
 * 旅のどの時点か。**0=出る前 / 1=道の上 / 2=帰ってから。**
 *
 * **画面が出てから呼ぶこと。** 静的書き出しなので、焼くと出発の日から
 * 17日ぶん「出る前」のままになる（`chapters.ts` の `looseStartNow` と同じ）。
 *
 * 日どりは持たない。`chapters.ts` の旅の章を見る——始まったかどうかは
 * `chapterSpan` が、いま道の上かは `looseStartNow` が、すでに答えを持っている。
 */
function tripPhase(now: Date): 0 | 1 | 2 {
  if (looseStartNow(now)) return 1;
  if (!TRIP_CHAPTER) return 0;
  return chapterSpan(TRIP_CHAPTER, now).from === null ? 0 : 2;
}

