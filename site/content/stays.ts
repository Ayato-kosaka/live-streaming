/**
 * 滞在の表。**いつ、どの国・街に居たか（予定を含む）を、手で書くのはここだけ**
 * （`docs/spec/model.md` の M-20。#1275）。
 *
 * 前は同じ事実を5か所に手で書いていた——`content/countries.ts` の `COUNTRIES[].stays` と
 * `AHEAD_COUNTRIES`、`content/chapters.ts` の章の `countries`、`components/isle/spec.ts` の
 * `GUIDES` と `ENTERED`。国を1つ越えるたびに最低3か所・ふつう5〜6か所を直していて（#664）、
 * 片方だけ直った日に面の上と下で国が食い違った。いまはどれもこの表から引く:
 *
 * | 引く側 | 引きかた |
 * | --- | --- |
 * | `COUNTRIES[].stays` | 国の記録（`countries.ts`）を持つ国の行 |
 * | `AHEAD_COUNTRIES` | まだ記録を持たない国の行（`name` を持つ行） |
 * | 章の `countries` | 期間が章と重なる行のうち、記録を持つ国（`content/stayChapters.ts` の `chapterCountrySlugs`） |
 * | 案内の出し分け（`GUIDES`） | `guide` を持つ行（`spec.ts` の `guidesOf`） |
 * | 国に入った日（`ENTERED`） | 行ぜんぶ |
 * | 毎晩の焼き直し | `python/stays.py`（`python/ts_read.py` の `read_stays` で読む） |
 *
 * ## 国を移った日に直すのは、この表だけ
 *
 * いまの行の `to` に出た日を入れ、つぎの国の行を足す。**ほかのファイルは触らない。**
 * 歩き終わった国に記録（見どころ・ひとことの紹介・`order`）を書くときは、`countries.ts` に
 * 国を足して、その国の行から `name` を消す（名前の持ち主が国の記録に移る）。
 * どちらかだけだと書き出しが止まる（`countries.ts` の頭の確かめ）。
 *
 * ## 行の決まり
 *
 * - **着いた順に並べる。** 読む側は並べ替えるが、人が読むのはこの順
 * - `from` は着いた日。**配信で確かめた日**（予定の日ではない）。先の日付も書ける（これから着く予定）
 * - `to` は出た日。**決まっていなければ空**（M-22。見立てで書かない）。空の行が「いまここ」で、
 *   多くて1つ（M-13）
 * - **境目の日は入った国が取る。** 国を移る日は、前の行の `to` とつぎの行の `from` が同じ日になってよい
 *   （朝は前の国、晩はつぎの国）。配信の振り分けは、つぎの国の `from` の前日で前の行を閉じる
 *   （`python/stays.py` の頭。`components/isle/spec.ts` の `staysOf` も同じ切りかた）
 * - `cities` は行った街。**まだ分からなければ空**（推測で埋めない）。空のあいだ、毎晩の焼き直しは
 *   国の名前を1つ置く（`python/stays.py` の `chapter_stays()`）。**街を入れると `cityStreams.ts` の
 *   欄の名前が変わる**（国の名前 → 街の名前）ので、入れる日に台本（`python/data/guide/<国>/…json`）の
 *   `streams.city` も揃える（`python/guidebook_bake.py` の注）
 * - `name` は**国の記録をまだ持たない国だけ**が持つ（名前の持ち主は国の記録。書き写さない）
 * - `guide` はその国の案内の面。**面の在る国だけ**に書く（押した先が無い札を建てない）。
 *   出すのは、その滞在の期間のあいだだけ（`components/isle/spec.ts` の `guidesOf`）
 *
 * ## 行どうしは重ねない
 *
 * 滞在は互いに重ならず、どれも本線の旅ちょうど1つの期間に収まる（M-12）。外れていれば
 * `content/stayChapters.ts` の `tripProblems` が書き出しを止める。**国でないものの行を作らない**（M-17）——
 * 前はイラン国境が国の行として居て、アルメニアの行と 04-29〜05-08 が重なり、同じ配信6本が両方の国に
 * 数えられていた（#1355）。国境まで歩いた区間は、アルメニアの中の地点（`cities` のメグリ）で、
 * 歩いたこと自体は枝の旅「イランまで歩く」（`content/chapters.ts`）が持つ。
 */

