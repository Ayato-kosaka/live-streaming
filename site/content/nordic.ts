/**
 * 移動のしかた。ヒッチハイクかどうかが、この企画ではいちばん大事な区別。
 * `van` は乗り合いのワゴン（ジョージアのマシュルートカ）。
 */
export type Move = "fly" | "hitch" | "ferry" | "walk" | "van";

export type Leg = {
  /**
   * 区間の名前。意見を区間ごとに分けて貼るときの札に使う（`【区間:riga-tallinn】`）。
   * **変えない。** 変えると、それまでに集まった道しるべが行方不明になる。
   */
  id: string;
  /** どこから */
  from: string;
  /** どこへ */
  to: string;
  move: Move;
  /** 距離(km)。飛行機とフェリーは目安。 */
  km?: number;
  /**
   * かかる時間。**あやとが言い切った区間と、切符から引き算できる区間だけ。**
   *
   * 陸路で本人が時間まで言ったのは2区間しかない（ワルシャワ→ビャウィストク
   * 2時間17分、ビャウィストク→ヴィリニュス 4時間14分）。
   * ほかの陸路に「半日」「1日」と書いていたことがあるが、あれは見立てで、
   * 同じ列に混ぜると2つの本物まで見立てに見える。**埋めない。**
   */
  time?: string;
  /** その区間の話。読んで面白いことだけ書く。 */
  note?: string;
  /**
   * その日の日付(YYYY-MM-DD)。
   *
   * 前は「切符のある2日だけ」だった。2026-09-06 にあやとが出発から
   * ストックホルムを発つ日まで**全部の日を言い切った**ので、いまは全区間にある。
   * ただしヒッチハイクなので、着く時刻は乗せてもらえた車しだいのまま。
   */
  date?: string;
  /** 決まっている時刻など、動かせない事実 */
  fixed?: string;
  /** 国が変わる区間なら、その国の slug */
  enters?: string;
  /** 泊まる予定 */
  stay?: string;
  /**
   * 寄り道。行って戻ってくる区間で、旅の進み方には数えない。
   * （`TripNow` の「いま／つぎ」は、これを外した一本道で組み立てる）
   */
  side?: boolean;
  /**
   * この区間の絵（`components/nordic/Marks.tsx` の名前）。
   * **区間ごとに必ず違うものにする。** 同じ印を10回並べると、
   * どの日も同じことをしているように見えてしまう。
   */
  art: string;
  /**
   * 通り道にあって、**寄るかどうかがまだ決まっていない街**。
   *
   * 通ると決まった街（`from` `to`）と同じ列に混ぜない。混ぜると、
   * 寄ると決まっているように読める。1日ぶんのページでは、この街だけ
   * 「寄るかどうかは、これから決まります」と断ってから出す。
   *
   * **見どころ（`content/nordic/*.json`）にある街だけを置く。**
   * 中身の無い街を並べても、押した先に何も無い。
   */
  maybe?: string[];
  /**
   * その区間のヒッチハイク。**この企画でいちばん中身の要るところ。**
   *
   * オーナーの言葉:
   *
   * > `/nordic/day/x` には、ヒッチハイク情報、ルート中のよりたい場所、
   * > その街固有の楽しみ方、などの情報があると良いと思います
   *
   * **事実と見立てを混ぜない。** `road` と `border` は地図で追える事実
   * （道路番号と、陸の国境の名前。国境は `python/build_nordic_map.py` の
   * `BORDERS` と同じもの）。`stand` と `hard` は**見立て**で、そう書いてある。
   * 画面でも「道と国境は地図から。立つ場所と難しさは見立て」と断って出す。
   */
  hitch?: {
    /** 乗る道。番号と名前だけ。走ってみないと分からないことは書かない */
    road: string;
    /** 陸の国境。越えるところの名前。無い区間もある */
    border?: string;
    /** どこで親指を上げるか。**見立て** */
    stand: string;
    /** 難しさ。1=みじかい 2=ふつう 3=山場。**見立て** */
    hard: 1 | 2 | 3;
    /** そう見ている理由。距離・国境・日の長さなど、数えられることから書く */
    why: string;
  };
  /**
   * その日、お金が要るもの。**実際に払うもの1つ。**
   *
   * 「1kmあたり◯円」にしない。何に使うか分からない金は出しづらいし、
   * 出したあとに何が変わったのかも分からない。
   *
   * 使い先は面のいちばん下の「応援する」だけ。旅程表には金額を出さない。
   * `yen` は空にしておける（泊まるところはまだ決まっていない）。
   */
  fare?: {
    /** 何に要るのか。「リガの一泊」のように、必ず物に紐づける */
    what: string;
    /** 円。決まっていないうちは付けない */
    yen?: number;
    /** 現地の値段。円に直す前の数字を添えると、何を見て決めたかが分かる */
    src?: string;
  };
  /**
   * わかれ道。**押すだけで答えられる、参加のいちばん下の段。**
   *
   * **本当に決まっていない分かれ目にしか置かない。** 決まっていることを
   * 聞いても、押した数はどこにも効かない。それは1回で見抜かれる。
   *
   * **問いは、それだけ読んで何の話か分かる形で書く。**
   * 「始発まで、空港で数時間あります」は、どこの空港のいつの話かが問いの中に無い。
   * オーナーに「何のこと？ ってなる」と止められた。場所と時と、
   * 何が分かれているのかを、問いの文そのものに入れる。
   * 上に出る「何日目・どこからどこへ」の一行（`Asks`）は、その念押しであって、
   * それを読まないと通じない問いは書かない。
   *
   * 字はここ（Git）にあって、サーバーは id と数しか持たない。
   * 変えてもいいのは `q` と `label` だけで、**`id` は変えない。**
   * 変えると、それまでに押された数が行方不明になる。
   */
  fork?: {
    /** 分かれ目の問い。答えが2つに割れるものだけ */
    q: string;
    /** 選択肢。2つ。id は `[a-z][a-z0-9-]{0,15}`、変えない */
    options: { id: string; label: string }[];
  };
};

