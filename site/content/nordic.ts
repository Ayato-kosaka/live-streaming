/**
 * その日に、実際に起きたこと。
 *
 * よていだけの旅程表は、出発前にしか読む理由がない。
 * 越えた日から順にこれが入ると、旅程表がそのまま日記になる。
 * 旅が終わったあとも `/nordic` が読み返される理由は、ここにしかない。
 *
 * **旅の最中は、ここに入らない。** ここを直すには Git を編集して commit して、
 * Hosting を手で起動しないと出ない。あやとはヒッチハイクをしている。
 * それは回らない。だから旅のあいだは Firestore に書いて、画面が出てから読む
 * （`docs/nordic-depart.md`・`components/nordic/DayLog.tsx`）。
 *
 * **ここは焼き付けた正本。** 旅が終わったら、Firestore の中身をここへ写して、
 * 以後は静的なものとして配る。読み返されるのは旅のあとのほうが長いので、
 * そのころには API に頼らないほうがいい。写すのは
 * `python/admin/nordic_log.py`（`{"op":"export"}`）が出す形をそのまま貼る。
 *
 * **鍵は旅程表の行（`Day.id`）。** 区間の id ではない。あやとがスマホから
 * 選ぶのは「何日目か」であって、「どの区間か」ではない。
 *
 * 空なら区画そのものを出さない。「まだ何も起きていません」と書くと、
 * 旅がうまくいっていないように読める。
 */
export type DayLog = {
  /** その日が実際に何日だったか（YYYY-MM-DD）。日にちの決まっていない行はこれで埋まる */
  date?: string;
  /** 何が起きたか。2〜3行。あとから読んで面白いことだけ書く */
  body: string;
  /** その日の配信。YouTube の videoId。無いときは行ごと出さない */
  video?: string;
};

