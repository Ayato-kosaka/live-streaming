/**
 * 旅のよてい。**オーナーが言い切った日を、言い切ったとおりに並べる。**
 *
 * 2026-09-06 に旅程がまるごと入れ替わった。**アウシュヴィッツとクラクフは無くなり**、
 * ビャウィストクのあとに**休息日が1日**入って、ストックホルムへは
 * **トゥルクからの夜行フェリー**で渡る。日付は出発から発つ日まで全部付いた。
 * 前にあった「予備の2日」は、休息日に置き換わって消えた。**戻さないこと。**
 *
 * **旅はストックホルムに着いて終わりではない。** そこから7泊して、
 * 9月27日にティラナへ発つまでが北欧旅（あやと 2026-09-06
 * 「ストックホルム出るまでが北欧旅です」）。だから旅程表の下に
 * 「着いた」と「旅のおわり」の2行がある（`components/nordic/GoalRow.tsx`）。
 *
 * ROUTE から機械的に組み立てていたのをやめて、ここは手で並べる。
 * 1日に1区間という決まりが、そもそも本人の言い方と合っていなかった。
 */
export type Day = {
  /** 何日目。**本人が言い切った日にだけ入る。** */
  n?: number;
  /** 数字の代わりに出す札。いまは「出発」と「ストックホルムで7泊」 */
  label?: string;
  /** 面の中の名前。上の司令塔から `#day-…` で飛んでくる。**変えない。** */
  id: string;
  /** 決まっている日付(YYYY-MM-DD) */
  date?: string;
  /**
   * その日を一行で。**1日ぶんのページに入る前に、どんな日か分かるようにする。**
   *
   * **区間のデータから読めることだけを書く。** 距離・移動のしかた・国境・
   * 区間の `note` にある事実。ここで新しい予定を作らない。
   */
  lead?: string;
  /** その日に動く区間 */
  legs?: Leg[];
  /**
   * 動かない日の街。**休息日だけが持つ。**
   *
   * 区間が無い日にもページが要る。休息日は「その街で何をするか」しか
   * 中身が無い日で、そこがいちばん読まれるところになる。
   */
  city?: string;
  /** 動かない日の絵。区間があるときは区間の絵を使う */
  art?: string;
  /** 動かない日の、寄るかもしれない街 */
  maybe?: string[];
  /** 動かない日のわかれ道。区間が無いので、行そのものにぶら下げる */
  fork?: Leg["fork"];
  /** その日の終わりに泊まるところ */
  stay?: string;
  /** その行に添える一行。区間の入っていない行はこれだけを持つ */
  say?: string;
  /** 区間の入っていない行。罫線と字だけにする */
  bare?: boolean;
};

const leg = (id: string) => {
  const l = ROUTE.find((x) => x.id === id);
  if (!l) throw new Error(`旅程表に無い区間: ${id}`);
  return l;
};

