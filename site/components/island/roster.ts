/**
 * 今日、島に出る人をえらぶ。
 *
 * ## あやとの決め（2026-09-15）
 *
 * > やっぱり、投げ銭よくしてくれる人が優先されるべき。けど、出席も大事。
 * > 額と出席まで欲しい。**投げ銭の頻度はどうでも良い。**
 * > 少額でも出席し続けてたら良い。**少額頻度高めで出席悪ければ意味ない。**
 * > **相対評価が良いかも。ランクづけを過去3ヶ月でして、スコアリングできそう。
 * > 額1位は皆勤と同じくらい重要**
 *
 * 見るのは2つだけ。**直近90日の投げ銭の総額**と、**直近90日の出席日数**。
 * どちらも**その3ヶ月での順位**を 0〜1 の点に直して、**足す**（掛けない）。
 * 掛けると額0の人の点が0になって、二度と島を歩けなくなる。
 * 足せば「出席だけでも出られる」と「額1位 ≒ 皆勤」が同時に立つ。
 *
 * **何回に分けて投げたかは見ない。** 点は総額の順位から決まるので、
 * 同じ額を10回に分けても1回で投げても同じ点になる。
 *
 * 点そのものを作るのは焼くほう（`python/build_residents.py`）。
 * ここは**焼いてある点を、今日の顔ぶれに直すだけ。**
 *
 * ## あやとの決め（2026-09-19 / issue #568）
 *
 * > Q1 A（直近90日で出席0日・投げ銭0 の人は、島に出さない）
 * > Q3 上位は固定気味で、下のほうだけ入れ替わる
 * > Q2 は任せる
 *
 * 前はこの2つが効いていなかった。重みが `1 + 2 × 点` の**一本の坂**だけだったので、
 * **点0の人も重み1を持って毎日の抽選に残り**、島の11人のうち
 * **4.2人が「3ヶ月なにもしていない人」**だった（4,000日の実測）。
 *
 * 直しかたは2つ。
 *
 *  1. **点0の人を候補から外す**（103人 → 44人）
 *  2. **上位 `FIXED_SEATS` 人を点の順で固定し、残りの席だけ抽選する**
 *
 * 外した経緯と、倍率を上げる案がなぜ効かなかったかは
 * `docs/island-misses.md` #175。
 *
 * 2 を「倍率を上げる」で近似しない。倍率は上も下も同時に固めるので、
 * 30倍にすると点0の人は減るかわりに**下も動かなくなる**。
 * 席を分ければ「上は毎日同じ顔・下は毎日入れ替わる」がそのまま書ける。
 */

import { rng } from "./geometry";

/** 抽選にかける人。`score` は `site/content/residents.ts` が焼いた 0〜1 の点。 */
export type Weighted = { days: number; score?: number };

/**
 * 点の順で**毎日そのまま座る**席の数（島は11〜12人）。
 *
 * **測って決めた値。** 本番の焼き込み（候補103人・うち点>0 は44人）で
 * 4,000日まわして、11人の島がどうなるかを数えた。
 *
 * | 固定席 | 毎日おなじ顔 | 抽選席に出入りする人 | 点0.9超の11人が島にいる率 | 点0.35以下の11人が島にいる率 | 前日と顔ぶれが同じ日 |
 * | --- | --- | --- | --- | --- | --- |
 * | 0人 | **0人**（＝Q3を満たさない） | 44人 | 30% | 18% | 0日 |
 * | 2人 | 2人 | 42人 | 39% | 16% | 0日 |
 * | 3人 | 3人 | 41人 | 45% | 15% | 0日 |
 * | **4人** | **4人** | **40人** | **50%** | **13%** | **0日** |
 * | 6人 | 6人 | 38人 | 62% | 10% | 0日 |
 * | 8人 | 8人 | 36人 | 76% | 6% | 0日 |
 * | 11人 | 11人 | **0人**（＝下が1人も入れ替わらない） | 100% | 0% | **3,999日** |
 *
 * **4人にした理由。**
 *
 * - **島の11席のうち4席（36%）が毎日そのまま。** 半分を超えると
 *   「下のほうだけ入れ替わる」ではなく「上半分が動かない」島になる。
 *   6人で55%、8人で73%。**固定席は島の半分を超えない**を上限にした
 * - **抽選が7席あり、40人が出入りする。** 前の日との差が毎日 5.75人。
 *   6人固定にすると抽選は5席まで痩せる
 * - **2人では「固定気味」に見えない。** 島の82%が毎日入れ替わるので、
 *   目で見えるものが今までと変わらない
 * - **点の並びに切れ目が無い。** 上から 0.995 / 0.980 / 0.966 / 0.956 /
 *   0.946 … と 0.01 刻みで続くので、「点で切れるところ」を席の数には
 *   できない。**席の側（11席のうち何席か）から決めた**
 *
 * 固定席から外れた上位の人も、抽選席では重い。点0.9超の11人は、
 * 固定4人を含めて**半分の日に島にいる**（公平なら 11/44 = 25%）。
 */
export const FIXED_SEATS = 4;

/**
 * 抽選席のなかで、点が満点の人は点が最下位の人の何倍えらばれやすいか。
 *
 * **3倍のまま据え置いた。ここを動かしても Q3 は作れない**と測って分かったため。
 * 固定席を0人にして倍率だけ上げると、4,000日で点0.9超の人が島にいる率は
 * **30%（3倍）→ 33%（10倍）→ 33%（30倍）**しか動かない。
 * 抽選に残る44人の点が 0.289〜0.995 に固まっていて、倍率を29倍にしても
 * 重みの比は 28.4 対 9.4（＝3倍）にしかならないから。
 *
 * 逆に上げすぎると**下も動かなくなる。** 倍率は上位と下位に同時に効くので、
 * 「上は固定・下は入れ替わる」を1つの坂では書けない。**席を分けるほう**で書いた。
 */
export const TOP_WEIGHT = 3;

/** 0〜1 に収める。焼き込みが壊れていても抽選だけは回るように。 */
function clamp01(v: number): number {
  return v < 0 ? 0 : v > 1 ? 1 : v;
}

/**
 * 値の一覧 → 0〜1 の点。**相対評価（順位）で決める。**
 *
 * 点 ＝ 自分より小さい値の人数 ÷ (人数 - 1)。
 *
 * **同着は全員おなじ点で、そのかたまりの「いちばん下」に付ける。**
 * かたまりの上や平均で付けると、投げ銭0円の人が数十人並んでいるだけで
 * その全員が真ん中あたりの点をもらう。それは
 * 「投げ銭よくしてくれる人が優先される」の逆になる。
 *
 * @param {number[]} values 値の一覧
 * @return {number[]} 同じ並びの点
 */
export function rankPoints(values: number[]): number[] {
  const n = values.length;
  if (n <= 1) return values.map(() => 0);
  const sorted = [...values].sort((a, b) => a - b);
  return values.map((v) => {
    // 自分より小さい値が何人いるか（二分探索）
    let lo = 0;
    let hi = n;
    while (lo < hi) {
      const mid = (lo + hi) >> 1;
      if (sorted[mid] < v) lo = mid + 1;
      else hi = mid;
    }
    return lo / (n - 1);
  });
}

/**
 * 一人ずつの点（0〜1）。
 *
 * ふだんは焼いてある `score` をそのまま使う。
 * **`score` を持たない人は、出席日数の順位だけで点を付ける。**
 * 焼き直しの前や、島の状態の口から来た受け皿のデータには点が無いので、
 * そこで全員を同じ重みに落とすと「よく来てくれている人ほど島にいる」が
 * 丸ごと消える。額が読めないぶんだけ弱くなる、に留める。
 *
 * @param {Weighted[]} all 候補ぜんぶ
 * @return {number[]} 同じ並びの点
 */
export function pointsOf(all: Weighted[]): number[] {
  const byDays = rankPoints(all.map((p) => p.days));
  return all.map((p, i) => (typeof p.score === "number" ? clamp01(p.score) : byDays[i]));
}

/**
 * 抽選の重み。点0で 1、点1で `TOP_WEIGHT`。
 *
 * **点0の人はそもそも抽選に入らない**（`liveOf`）ので、この 1 が使われるのは
 * 名簿が痩せた日の穴埋めだけ。
 *
 * @param {Weighted[]} all 候補ぜんぶ
 * @return {number[]} 同じ並びの重み
 */
export function weightsOf(all: Weighted[]): number[] {
  return pointsOf(all).map((s) => 1 + (TOP_WEIGHT - 1) * s);
}

/**
 * 島に出す人と、出さない人。**点の大きい順に並べて返す。**
 *
 * `live` が「直近90日で、出席したか投げ銭してくれた人」。
 * `rest` が点0——**3ヶ月なにもしていない人**で、ふだんは島に出さない
 * （あやとの決め 2026-09-19 / #568 Q1=A）。
 *
 * 同点は焼き込みの並びのまま（`build_residents.py` が出席の多い順に焼く）。
 * **日によって入れ替わらないように、乱数を混ぜない。**
 *
 * @param {Weighted[]} all 候補ぜんぶ
 * @return {object} 点の大きい順の番号。`live` が出す人、`rest` が点0の人
 */
export function liveOf(all: Weighted[]): { live: number[]; rest: number[]; points: number[] } {
  const points = pointsOf(all);
  const order = points
    .map((p, i) => ({ p, i }))
    .sort((a, b) => b.p - a.p || a.i - b.i)
    .map((x) => x.i);
  return {
    live: order.filter((i) => points[i] > 0),
    rest: order.filter((i) => points[i] <= 0),
    points,
  };
}

/**
 * 重み付きの復元なし抽選。`乱数^(1/重み)` の大きい順に `n` 人取る。
 * 選ばれる回数が重みに比例する。
 *
 * @param {number[]} idx 抽選にかける人の番号
 * @param {number[]} w `idx` と同じ並びの重み
 * @param {number} n 何人取るか
 * @param {function} r その日の乱数
 * @return {number[]} 選ばれた番号
 */
function draw(idx: number[], w: number[], n: number, r: () => number): number[] {
  if (n <= 0) return [];
  if (idx.length <= n) return [...idx];
  return idx
    .map((i, k) => ({ i, key: Math.pow(Math.max(r(), 1e-9), 1 / w[k]) }))
    .sort((a, b) => b.key - a.key)
    .slice(0, n)
    .map((x) => x.i);
}

/**
 * 今日、島に出ている人。
 *
 * **席を2つに分ける。**
 *
 *  - **固定席（`FIXED_SEATS` 人）** … 点のいちばん上から、毎日そのまま
 *  - **抽選席（残り）** … そこから下を、点を重みにした日替わりの抽選で
 *
 * 全員を毎日ぜんぶ歩かせると島が人で埋まるし、上位から固定で選ぶだけだと
 * **昨日と今日で島がまったく同じ**になる（`docs/island-play.md` 2章）。
 * 逆に全席を抽選にすると、揺らしが順位をほぼ打ち消してしまう（#568）。
 * 分ければ両方立つ。
 *
 * **点0の人（3ヶ月なにもしていない人）は、どちらの席にも入らない。**
 * ただし**名簿が痩せた日**——新しい章の頭や、取り込みが落ちて出席が
 * 数えられなかった日——は点>0 が `max` 人に届かない。
 * そのときだけ、点0の人から日替わりで穴を埋める。**空の島は出さない。**
 *
 * @param {T[]} all 候補ぜんぶ
 * @param {number} max 一度に島を歩く人数
 * @param {number} day 日本時間の通算日数
 * @return {T[]} 今日の顔ぶれ
 */
export function rosterOf<T extends Weighted>(all: T[], max: number, day: number): T[] {
  if (all.length <= max) return all;
  const r = rng((day * 2654435761) >>> 0);
  const { live, rest } = liveOf(all);
  const w = weightsOf(all);

  // 名簿が痩せた日。点>0 の全員を出したうえで、足りないぶんだけ点0から
  const chosen = live.length < max
    ? [...live, ...draw(rest, rest.map(() => 1), max - live.length, r)]
    : (() => {
      const fixed = live.slice(0, Math.min(FIXED_SEATS, max));
      const pool = live.slice(fixed.length);
      return [...fixed, ...draw(pool, pool.map((i) => w[i]), max - fixed.length, r)];
    })();

  // 並びは日替わりにする。持ち場と立ち位置は配列の順で決まるので
  // （`villagers.ts` の `assignPosts`）、点の順のまま返すと
  // 固定席の人が毎日おなじ場所に立つ
  for (let i = chosen.length - 1; i > 0; i--) {
    const j = Math.floor(r() * (i + 1));
    [chosen[i], chosen[j]] = [chosen[j], chosen[i]];
  }
  return chosen.map((i) => all[i]);
}
