/**
 * 日本語の見出しを、**渡した切れ目でだけ折る。**
 *
 * ## なぜ要るか（2026-10-12）
 *
 * `/next` の0件の見出しが、390px でこう折れていた。
 *
 * ```
 * 日にちの決まった企画
 * は、いまはありません
 * ```
 *
 * **行頭に「は、」が来ている。** 「企画」で切れているので、一瞬べつの文に見える。
 * 表紙の同じ字も、360px で**「ん」1文字だけ**が2行目に落ちていた。
 *
 * `text-wrap: balance`（`.panel > h2` には前から付いている）は**行の長さを
 * 均すだけ**で、どこで切るかは選ばない。均した結果が 10字/10字 なので、
 * ちょうど「企画｜は、」で切れる。`word-break: auto-phrase`（文節で折る）は
 * 実測では良い答えを出すが、**Chromium にしか無い**ので、よその browser では
 * 元の折れ方に戻る。
 *
 * だから、**折ってよい場所そのものを減らす。** 渡した塊ひとつひとつを
 * `white-space: nowrap` にすると、折れるのは塊と塊のあいだだけになる。
 * CSS の対応を待たず、どの browser でも、どの幅でも同じところで折れる。
 *
 * 実測（Chromium 141。`/next` の見出し・幅ごとの行）:
 *
 * | 幅 | 入れる前 | 入れたあと |
 * | --- | --- | --- |
 * | 320〜430px | 「日にちの決まった企画」「**は、**いまはありません」 | 「日にちの決まった企画は、」「いまはありません」 |
 * | 768px〜 | 1行 | 1行（変わらない） |
 *
 * ## 使うとき
 *
 * ```tsx
 * <Phrase parts={NO_PLAN_TITLE} />
 * ```
 *
 * **塊は、1つが器に収まる長さにする。** 収まらない塊は中で折れるので、
 * そこは今までどおりの折れ方になる（はみ出しはしない）。
 */
export default function Phrase({ parts, className }: { parts: string[]; className?: string }) {
  return (
    <span className={className ? `phrase ${className}` : "phrase"}>
      {parts.map((s) => (
        <span key={s}>{s}</span>
      ))}
    </span>
  );
}
