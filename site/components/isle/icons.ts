/**
 * 島に建つものの絵を、**章ごとに持ち替える表。**
 *
 * あやとの言葉（2026-10-07）:「あやと島のそれぞれの島が見た目が似すぎてて
 * 全然面白さがないので、その島の特徴もちょっと出せるように」。
 *
 * ## 変えるのは絵だけ。役割は動かさない
 *
 * 札に出る名前（`label`）・押したときに開くもの（`id`）・島のどこに建つか
 * （並び順）は**6章ぜんぶ同じ。** 「この島のこと」を押せば、どの島でも
 * 同じ場所で同じものが開く。ここが崩れたら、島ごとに作りの違う面になって
 * しまう——**押す人にとっては、同じ島めぐりの続き**でないといけない。
 *
 * だから `spec.ts` は役割ごとに**既定の絵**を持ったままで、ここは
 * 「その章だけ、この絵に差し替える」という上書きだけを持つ。
 * 章がここに無ければ既定の絵が出るので、**章を1つ足しても島は建つ。**
 *
 * ## なぜ要ったか（2026-10-07 の実測）
 *
 * 6島に出ていた建物の絵は **9種しかなかった。** `statue`（この島のこと）と
 * `pier`（となりの島へ）は **6島ぜんぶに同じ絵**で立っていて、
 * 建物の絵の重なり（Jaccard）は平均 63%、**中東とコーカサスは 100%**
 * ——つまり**絵の上では同じ島**だった。
 * 手持ちのスプライトは 311種あって、6島に出ていたのは 34種（11%）。
 *
 * ## 置いてよい絵の決まり
 *
 * - **その土地に在るものだけ。** 島が嘘をつかない（`docs/island-atlas.md` 3章）
 * - **役割が読めること。** 「この島のこと」は6島とも「石の記念物」、
 *   「となりの島へ」は6島とも「舟のつく場所」。
 *   絵の**種類**は変わっても、**何のための場所か**は変わらない
 * - **札の字と矛盾しないこと。** 「となりの島へ／船で渡る」に橋を置かない
 *   （舟で渡ると書いてあるのに橋が立っていたら、どちらかが嘘になる）
 * - **同じ島の中で2つの役割が同じ絵にならないこと**（`icons_selftest.mjs` が見る）
 *
 * 名前は `site/public/sprites/` に在るものだけ。**在るかどうかは
 * `site/selftest/icons_selftest.mjs` が数えている**ので、綴りを間違えたら赤くなる。
 */

