/**
 * その章の、その役割の絵。**章に上書きが無ければ既定の絵をそのまま返す。**
 *
 * @param slug     章（`content/chapters.ts` の slug）。表紙の島のように
 *                 章を持たない島は渡さない——既定の絵で建つ
 * @param role     役割の id（`IslePlaceSpec.id`）
 * @param fallback 既定の絵
 */
export function isleIcon(slug: string | undefined, role: string, fallback: string): string {
  return (slug && ISLE_ICONS[slug]?.[role]) || fallback;
}
