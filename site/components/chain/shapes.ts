/** その章が回った土地。国の region の多数決で決める。国が無ければ温帯 */
export function groundOf(regions: string[]): Ground {
  let dry = 0;
  for (const r of regions) if (r === "中東・アフリカ") dry++;
  return dry * 2 > regions.length ? "dry" : "temperate";
}

/** 文字列から決まる、いつも同じ数。島の形の種にする */
function hashOf(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619) >>> 0;
  return h >>> 0;
}

/**
 * その章の島の絵。表にあればそれ、無ければ土地から作る。
 *
 * @param slug   章の slug
 * @param regions その章で回った国の region（`content/countries.ts`）
 */
export function artOf(slug: string, regions: string[] = []): IslandArt {
  const known = ISLAND_ART[slug];
  if (known) return known;
  const seed = hashOf(slug);
  const g = groundOf(regions);
  const r = rng(seed);
  /* かたち。**手で形を与えた島と同じ 32方位**で作る（16方位だと湾も岬も入らない）。
     乱数を1点ずつ振るとギザギザになるので、周期の違う波を3本重ねて、
     隣どうしがつながったままにする（geometry の wobble と同じ考え）。

     振れ幅は ±36%。**±22% だと真円にしか見えなかった**——手で形を与えた
     6島が 1.8〜3.6倍の振れ幅を持っているので、表に無い章だけ
     じゃがいもに戻るのでは意味がない。
     そのうえで、**細い入り江をひとつ**（`cut`）だけ刻む。1本あれば
     「どこかに湾のある島」になって、ほかの章と見分けがつく。 */
  const ph = [r() * Math.PI * 2, r() * Math.PI * 2, r() * Math.PI * 2];
  const wv = [2 + Math.floor(r() * 3), 5 + Math.floor(r() * 4), 9 + Math.floor(r() * 5)];
  const cut = Math.floor(r() * 32);
  const radii = Array.from({ length: 32 }, (_, i) => {
    const a = (i / 32) * Math.PI * 2;
    const v =
      1 +
      Math.sin(a * wv[0] + ph[0]) * 0.22 +
      Math.sin(a * wv[1] + ph[1]) * 0.1 +
      Math.sin(a * wv[2] + ph[2]) * 0.04;
    return Math.round((i === cut ? v * 0.5 : v) * 100) / 100;
  });
  return { radii, squash: 0.62, props: PLANTS_OF[g], theme: THEME_OF[g] || undefined, seed };
}

/** 島の色。表に無い章は土地から決まる */
export const GROUND_ART: Record<Ground, IslandArt["props"]> = PLANTS_OF;
