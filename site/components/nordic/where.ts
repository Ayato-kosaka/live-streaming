/**
 * きょう、旅のどこにいるはずか。**旅程の日付から引く。**
 *
 * ここが無かったあいだ、いる場所の出どころは `/island-api/state` の
 * `current.place`——**あやとが手で打つ1本の文字列**だけだった。
 * その字は出発の1週間前（2026-09-04「ジョージア・トビリシ」）で止まっていて、
 * 旅の17日間、あやとは走っている車の中にいる。打ち直せない。
 *
 * 実際に起きていたこと（旅の2日目に本番を撮って確認）:
 *
 *   - 主役の箱が「いま ジョージア・トビリシ → めざす ストックホルム」
 *   - 残り距離が「ストックホルムまで 数えています」のまま永久に止まる
 *   - 旅程表の「いま、ここ」が12行ぜんぶ出ない
 *   - 航路図の「いま ここ」ピンがどこにも立たない
 *
 * **1本の文字列に4つがぶら下がっていて、人が毎日タイプしないと動かなかった。**
 * 答えは同じページに載っている。旅程表が「2日目 9月13日(日) ワルシャワ →
 * ビャウィストク」と日付つきで持っている（`docs/island-standards.md` 8
 * 「名簿・一覧を手で作らない。元のデータから導出する」）。
 *
 * だから一次情報を入れ替える。**日付から引いた街が既定で、手打ちは上書き。**
 * 打ってあればそちらが勝つ（`placeOutdated` で新しさを見る・`lib/stay.ts`）。
 *
 * **ただし、日付から引いたものは「予定」であって「いま」ではない。**
 * ヒッチハイクなので、乗せてもらえなければその日は進まない。
 * 呼ぶ側は、どちらから引いたのかで言い方を変えること
 * （「いま ワルシャワ」と「きょうは ワルシャワ」は同じ強さで言わない）。
 *
 * 街の表はここに持たない。突き合わせる並びは呼ぶ側が渡す
 * （`docs/island-misses.md` #3）。
 */

/** 旅程から引くのに要る日付だけ。街の名前も id も、ここでは見ない。 */
export type PlanStop = {
  /** ここを発つ日(YYYY-MM-DD)。終点は持たない */
  leaveOn?: string;
  /** ここへ着く日(YYYY-MM-DD)。出発地は持たない */
  arriveOn?: string;
};

/**
 * 旅をしている土地の暦で、きょうの日付(YYYY-MM-DD)。
 *
 * **日本時間で切らない。** 旅程の日付はどれも現地の日付で、
 * 日本時間の 00:00 は現地の前日 17:00。日本の夜のあいだじゅう、
 * 画面が翌日の区間を出すことになる。
 *
 * 中央ヨーロッパ夏時間(UTC+2)で切る。バルト三国とフィンランドは +3 だが、
 * ずれるのは現地の 00:00〜01:00 のあいだだけで、そこは走っていない。
 */
export function tripDate(now: Date = new Date()): string {
  return new Date(now.getTime() + 2 * 3600_000).toISOString().slice(0, 10);
}

/**
 * きょうの居どころ。`stops` の何番目か。分からなければ `null`。
 *
 * - **動く日は、その日に発つ街。** 朝そこにいて、夕方に次の街へ着く。
 *   1日に2区間ある日（タリン→ヘルシンキ→ストックホルム）は、最初に発つ街
 * - **動かない日は、最後に着いた街。** 休息日はこれで決まる
 * - 旅が終わる日（`until`）より後は `null`。予定が尽きたあとも
 *   終点を出し続けると、旅の1ヶ月後に「きょうは ストックホルム」と言う
 */
export function planStop(
  stops: readonly PlanStop[],
  today: string | null,
  until?: string,
): number | null {
  if (!today) return null;
  if (until && today > until) return null;
  const go = stops.findIndex((s) => s.leaveOn === today);
  if (go >= 0) return go;
  let at = -1;
  for (let i = 0; i < stops.length; i++) {
    const a = stops[i].arriveOn;
    if (a && a <= today) at = i;
  }
  return at >= 0 ? at : null;
}
