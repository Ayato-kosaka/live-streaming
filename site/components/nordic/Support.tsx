"use client";

import { useFund } from "./fund";

/**
 * 応援。**面のいちばん下に、これだけの区画として置く。**
 *
 * ここは前まで、旅程の一日ずつに「足代の席」として混ぜてあった。
 * 旅の話とお金の話を1つの言い方に押し込んだせいで、どちらも読みにくくなった
 * （`docs/nordic-fund.md` 「捨てた設計」）。分ける。
 *
 * 出す数字は**1つだけ。いくら集まっているか。**
 *   - 誰がいくら出したかは出さない。順位表も作らない。出す人は60人しかいなくて、
 *     上位は常連で固定される。中央値320円が1万円の隣に並ぶと、320円が恥ずかしくなる
 *   - 目標に対するバーを出さない。届かない絵は「みんなが応えなかった」に見える
 *   - 1円も読めないときは、数字の行ごと消す。0円は「誰も出していない」に見える
 *     （`GET /island-api/fund` は、そのために 200 で 0 を返さず 503 を返す）
 *
 * **出すのは `total`。配信の豚の貯金箱とそっくり同じ数字にする。**
 *
 * ここは `given`（人が実際に出した額）を出していた。起点（負の数）を含まないので
 * 「出してくれた額」としては正しい、という理屈だったが、**その理屈は捨てる。**
 * あやとの指摘（2026-09-06）「これ金額が貯金箱と違うない？」。
 * 実際、画面が 287,446円 と言っている横で、視聴者さんが毎晩見ている貯金箱は
 * 37,800円 だった。**同じものを指す数字が2つあるほうが、どちらが正しいかより害が大きい。**
 * 見ている人は貯金箱を先に見ているので、サイトのほうを合わせる。
 *
 * **人数も出さない**（あやとの指示「何人かは出なくて良い」）。
 * 額と人数を並べると、割り算されて「1人あたりいくら」が読めてしまう。
 *
 * ## Doneru のぶんが止まっている日だけ、もう1行足す（#294）
 *
 * Doneru の寄付は cookie ひとつで取りに行っていて、切れた日から
 * 貯金箱に入らなくなる。**額が減るのではなく、増えるのが止まる。**
 * 嘘ではないが、出してくれた人から見れば自分のぶんが出てこない。
 *
 * 出すのはこの数字のすぐ下。**数字と同じ場所でないと意味が無い**——
 * 読む人にとっての事実は「いまの数字は◯月◯日までのぶん」だけで、
 * それは数字から離れた場所に置いた瞬間、何の話か分からなくなる。
 *
 * 決めごとが3つ。
 *
 *   - **元気なときは1文字も足さない。** 口が `doneruAsOf` を返した日だけ出る
 *   - **警告にしない。** 赤くしない、印を付けない、驚かせない。
 *     どうぶつの森の温度のまま、いつ着くかを言う
 *   - **止まっているか分からない日は、黙る。** 額そのものが読めない日は
 *     この区画ごと出ない（`f` が null）ので、そこは自然にそろう
 */

const yen = (n: number) => `${n.toLocaleString()}円`;

/**
 * 「2026-09-12」を「9月12日」に。
 *
 * **年をまたいだときだけ年を出す。** ふだんは要らないが、止まったまま年を
 * またぐと「9月6日」が去年なのか今年なのか読めなくなる。
 * 今日の切り方は島じゅうと同じ日本時間（`lib/nightly.ts` の `jstNow`）。
 * ここは口が返ってから描くところなので、本物の時計を見てよい。
 */
const jp = (day: string) => {
  const [y, m, d] = day.split("-");
  const thisYear = new Date(Date.now() + 9 * 3600 * 1000).toISOString().slice(0, 4);
  return `${y === thisYear ? "" : `${Number(y)}年`}${Number(m)}月${Number(d)}日`;
};

export default function Support() {
  const f = useFund();
  if (!f) return null;
  return (
    <>
      <p className="nback-now">
        いま <b>{yen(f.total)}</b> 集まっています。
      </p>
      {/* **2文を改行で割らない。** JSX の改行はそのまま空白になるので、
          「入っています。␣そのあとに」と1つ空いて出る（実測）。 */}
      {f.asOf && (
        <p className="nback-asof">
          Doneru のぶんは、<b>{jp(f.asOf)}</b> まで入っています。そのあとに届いたぶんも、あとからちゃんと入ります。
        </p>
      )}
    </>
  );
}
