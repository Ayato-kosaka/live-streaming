/**
 * 名前の頭の1文字。**先頭の `@` は飛ばす。**
 *
 * 絵が出せないときに出る、最後の受け皿。看板の右はし（`MeButton`）と
 * じぶんのこと（`MyPage`）の両方で使う。**同じ人が2か所で違う字になると、
 * 別人に見える。**
 *
 * あやとの名前は `@あやとグルメアプリ`。そのまま1文字目を取ると
 * **「@」だけが出る**（2026-09-09 に本番でそうなっていた）。YouTube の
 * ハンドルはみんな `@` で始まるので、絵の無い人は全員そうなる。
 *
 * 記号を飛ばして、最初の「字らしい字」を取る。無ければ「?」。
 */
export function firstLetter(name?: string): string {
  for (const ch of name || "") {
    if (/[\p{L}\p{N}]/u.test(ch)) return ch;
  }
  return "?";
}
