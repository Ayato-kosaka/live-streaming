#!/usr/bin/env python3
"""**出す前の関所。** あやとに2回以上言われた投稿・進めかたの指摘を、`post.py` の段で数えて止める。

    python3 tools/shorts/post/preflight.py post <post_X.json> --edit <edit_X.json>   # send と同じ検査（記事・クレジット・BGM・往復）
    python3 tools/shorts/post/preflight.py issue-text <原稿のコメント.md>             # 制作 issue に出す原稿が、貼れる字か（F-098）
    python3 tools/shorts/post/preflight.py approval <あやとのコメントの URL>          # 承認に数えてよい、あやと本人のコメントか（F-002）
    python3 tools/shorts/post/preflight.py audit                                      # 台帳: Instagram の抜け（F-090）・止まった pending（F-085）

終了コード 0=通る / 1=止める / 2=読めない。

`post.py` が段ごとに呼ぶ（下の表）。帳面（`references/ayato_feedback.md`）の当てる場所の `post:<関所>` は、ここの `GATES` の鍵
（`tools/shorts/feedback/ledger.py --check` が、名前がコードに在るかを引く）。

| 関所 | 帳面 | どの段で | 何を数えて止めるか |
| --- | --- | --- | --- |
| `approval` | F-002 | 投稿の段（yt-draft・tt-post・ig-post） | `--approval <コメントの URL>` が無い・あやと本人のコメントでない（署名 `Generated by` つき・bot の呼び出し・ほかの書き手）。通ったらコメントID を台帳の行（`approval`）に残す。**字の中身は読まない**（「A」「全部」「12/1」をどう読むかは担当が読む。機械が書式で読み分けない＝F-002 の決まり） |
| `one` | F-085 | 投稿の段 | ほかの案の投稿が `pending` のまま（ONE_HOURS 時間以内に始めた）。1本を出し切ってから次へ |
| `article` | F-097 | send | YouTube の説明・TikTok のキャプション（・Instagram のキャプション）に島の記事（`https://ayato-arigato.com/travel/…`）が無い |
| `credit` | F-038 | send | ポケットサウンドのクレジット（`pocket-se.info`）と TikTok の `#ポケットサウンド` が無い（曲がクシコス・ポストの回） |
| `bgm` | F-038 | send（`--edit`） | 指示書（edit_*.json）の BGM がポケットサウンドの「クシコス・ポスト」（`pocket_csikos*.mp3`）でない。あやとが別の曲に決めた回は `bgm.not_csikos` にそのコメントの URL |
| `rounds` | F-044 | send（`--edit`） | あやとに見せた版（`shorts/videos/<id>/p<N>`）が ROUNDS_MAX を越えたのに、`--rounds-why` で訳を書いていない |
| `instagram` | F-090 | clean・audit | YouTube・TikTok に出した案（2026-11-22 から）に、Instagram の done の行が無い |
| `plain` | F-098 | issue-text | 原稿のコメントに、`<details>` の外の表・囲みの中の欄の区切り（`|`）・行番号・秒・【】の印がある |
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = "Ayato-kosaka/live-streaming"

GATES = {
    "approval": "F-002 承認に数えるのは、あやと本人のコメントだけ（署名・呼び出しは数えない）。ID を台帳に残す",
    "one": "F-085 ほかの案の投稿が pending のまま、次の案を出さない（1本ずつ仕上げる）",
    "article": "F-097 投稿文に島の記事へのリンクが無ければ止める",
    "credit": "F-038 ポケットサウンドのクレジットが投稿文に無ければ止める",
    "bgm": "F-038 指示書の BGM がポケットサウンドの「クシコス・ポスト」でなければ止める",
    "rounds": "F-044 あやとに見せた版の数が上限を越えたら、訳を書くまで止める",
    "instagram": "F-090 YouTube・TikTok に出した案に Instagram の行が無ければ止める",
    "plain": "F-098 制作 issue に出す原稿が表・欄の区切りなら止める",
}

ARTICLE = re.compile(r"https://ayato-arigato\.com/travel/[\w/-]+")
CREDIT = "pocket-se.info"
CREDIT_TAG = "#ポケットサウンド"
CSIKOS = re.compile(r"pocket[_-]?csikos", re.I)
APPROVED_BY = re.compile(r"https://github\.com/" + re.escape(REPO) + r"/issues/\d+#issuecomment-\d+")
COMMENT = re.compile(r"(?:https://github\.com/" + re.escape(REPO) + r"/issues/(\d+)#issuecomment-)?(\d+)$")
IG_FROM = "2026-11-22"   # F-090（#1353）: この日から Instagram にも出す
ONE_HOURS = 6.0          # これより前に始めた pending は、止まった記録（audit で出す）。並べて出している印にはしない
ROUNDS_MAX = 3           # F-044「往復は半分に」。11月のあやとに見せた版は、多い回で5（ルーマニアの3本の p5）
VERSION_DIR = re.compile(r"p\d+$")


# ---------- F-002 承認 ----------

def _is_ayato():
    """あやと本人のコメントかの見分け（`tools/shorts/feedback/watch.py` の `is_ayato`。写さずに借りる）。"""
    root = HERE.parents[2]
    for p in (root / "python", root / "tools/shorts/feedback"):
        if str(p) not in sys.path:
            sys.path.insert(0, str(p))
    from watch import is_ayato  # noqa: E402
    return is_ayato


def fetch_comment(cid: int) -> dict:
    """issue のコメント1件（gh の API）。読めなければ例外。"""
    out = subprocess.run(["gh", "api", f"repos/{REPO}/issues/comments/{cid}"], capture_output=True, text=True,
                         timeout=60, check=False)
    if out.returncode != 0:
        raise OSError(f"gh api が読めない（{out.returncode}）: {out.stderr.strip()[:200]}")
    return json.loads(out.stdout)


FETCH = fetch_comment   # 見張り（preflight_selftest.py）が偽物に差し替える


def approval(ref: str | None, fetch=None, is_ayato=None) -> tuple:
    """（コメントID, 止める訳か None）。承認に数えてよいのは、あやと本人のコメントだけ。字の中身は読まない。"""
    if not ref:
        return None, ("止めた: 承認のコメントが無い。--approval <あやとが「出して」「A」などと書いたコメントの URL> を付ける"
                      "（帳面 F-002。数えるのはあやと本人のコメントだけ）")
    m = COMMENT.fullmatch(ref.strip())
    if not m:
        return None, f"止めた: --approval は issue のコメントの URL か ID: {ref}"
    cid = int(m.group(2))
    try:
        c = (fetch or FETCH)(cid)
    except (OSError, ValueError) as e:
        return None, f"止めた: 承認のコメント {cid} を読めない（{e}）"
    if not (is_ayato or _is_ayato())(c):
        who = (c.get("user") or {}).get("login") or "?"
        return None, (f"止めた: コメント {cid} はあやと本人の言葉ではない（書き手 {who}・こちらの署名・bot の呼び出しのどれか）。"
                      "承認に数えるのは、あやとが自分で書いたコメントだけ（F-002）")
    return cid, None


# ---------- F-085 1本ずつ・F-090 Instagram ----------

def _at(s: str) -> datetime:
    return datetime.fromisoformat(s.replace("Z", "+00:00"))


def latest_rows(rows: list) -> list:
    """動画 × 場所ごとの、いちばん新しい記録（後ろが勝つ。`posted.latest` と同じ）。"""
    last = {}
    for r in rows:
        last[(r["sha256"], r["place"])] = r
    return list(last.values())


def others_pending(rows: list, plan: str, now: datetime | None = None, hours: float = ONE_HOURS) -> list:
    """ほかの案の、ONE_HOURS 時間以内に始めた pending（1本ずつ。F-085）。"""
    now = now or datetime.now(timezone.utc)
    return [r for r in latest_rows(rows)
            if r["state"] == "pending" and r["plan"] != plan and now - _at(r["at"]) < timedelta(hours=hours)]


def stale_pending(rows: list, now: datetime | None = None, hours: float = ONE_HOURS) -> list:
    now = now or datetime.now(timezone.utc)
    return [r for r in latest_rows(rows) if r["state"] == "pending" and now - _at(r["at"]) >= timedelta(hours=hours)]


def ig_missing(rows: list, prefix: str = "") -> list:
    """YouTube か TikTok に done で出した案（IG_FROM から）のうち、Instagram の done が無い案。prefix で動画を絞る。"""
    done: dict = {}
    for r in rows:
        if r["state"] == "done" and r["plan"].startswith(prefix):
            done.setdefault(r["plan"], {}).setdefault(r["place"], r["at"])
    return sorted(p for p, v in done.items()
                  if "instagram" not in v and any(v.get(k, "") >= IG_FROM for k in ("youtube", "tiktok")))


# ---------- F-097 記事・F-038 クレジットと BGM・F-044 往復 ----------

def texts(post: dict) -> list:
    """（どこ, 字）。YouTube の説明・TikTok のキャプション・Instagram のキャプション（あれば）。"""
    out = [("YouTube の説明", (post.get("youtube") or {}).get("description") or ""),
           ("TikTok のキャプション", (post.get("tiktok") or {}).get("caption") or "")]
    ig = (post.get("instagram") or {}).get("caption")
    if ig is not None:
        out.append(("Instagram のキャプション", ig))
    return out


def article_why(post: dict) -> list:
    return [f"{where}に島の記事のリンク（https://ayato-arigato.com/travel/…）が無い。記事を書いて、ショート → 記事・記事 → ショートの"
            "双方向にする（F-097）" for where, t in texts(post) if not ARTICLE.search(t)]


def credit_why(post: dict) -> list:
    out = [f"{where}にポケットサウンドのクレジット（{CREDIT}）が無い（F-038）" for where, t in texts(post) if CREDIT not in t]
    if CREDIT_TAG not in ((post.get("tiktok") or {}).get("caption") or ""):
        out.append(f"TikTok のキャプションに {CREDIT_TAG} が無い（ポケットサウンドの規約。F-038）")
    return out


def bgm_why(edit: dict) -> list:
    b = edit.get("bgm") or {}
    name = os.path.basename(str(b.get("path") or ""))
    if CSIKOS.search(name):
        return []
    if APPROVED_BY.search(str(b.get("not_csikos") or "")):
        return []
    return [f"指示書の BGM が「{name or '無し'}」で、ポケットサウンドの「クシコス・ポスト」（pocket_csikos.mp3）ではない。"
            "あやとが別の曲に決めた回は、bgm.not_csikos にそのコメントの URL を書く（F-038）"]


def rounds(edit_path: Path) -> int:
    """あやとに見せた版の数（`shorts/videos/<id>/p<N>` の数）。指示書が版の置き場に無ければ 0。"""
    d = edit_path.resolve().parent
    if not VERSION_DIR.fullmatch(d.name):
        return 0
    return sum(1 for x in d.parent.iterdir() if x.is_dir() and VERSION_DIR.fullmatch(x.name))


def rounds_why(edit_path: Path, why: str | None) -> list:
    n = rounds(edit_path)
    if n <= ROUNDS_MAX or (why or "").strip():
        return []
    return [f"あやとに見せた版が {n}回（上限 {ROUNDS_MAX}）。どこで往復が増えたか・頼む文のどこを直したかを --rounds-why に1行で書く（F-044）"]


def send_problems(post: dict, edit_path: Path | None, why: str | None = None) -> list:
    """send の前に数えること（記事・クレジット・BGM・往復）。止める訳の並び（空なら通す）。"""
    out = article_why(post)
    if edit_path is None:
        return out + ["指示書が無い。--edit <その版の edit_*.json> を付ける（BGM と往復の数を数える。F-038・F-044）"]
    try:
        edit = json.loads(Path(edit_path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        return out + [f"指示書 {edit_path} を読めない: {e}"]
    out += bgm_why(edit)
    if CSIKOS.search(os.path.basename(str((edit.get("bgm") or {}).get("path") or ""))):
        out += credit_why(post)   # あやとが別の曲に決めた回（not_csikos）は、その曲の決まりで書く
    return out + rounds_why(Path(edit_path), why)


# ---------- F-098 貼れる字 ----------

TABLE = re.compile(r"^\s*\|.*\|\s*$")
FENCE = re.compile(r"^\s*(```|~~~)")
IN_FENCE_BAD = ((re.compile(r"\|"), "欄の区切り（|）"), (re.compile(r"^\s*\d+\s*[.:：、)）]"), "行番号"),
                (re.compile(r"\d+(\.\d+)?秒"), "秒"), (re.compile(r"【[^】]*】"), "【】の印"))


def plain_why(text: str) -> list:
    """制作 issue の原稿のコメントが、そのまま貼れる字か（F-098）。止める訳の並び。"""
    out, fence, details = [], False, 0
    for no, ln in enumerate(text.splitlines(), 1):
        low = ln.strip().lower()
        if FENCE.match(ln):
            fence = not fence
            continue
        if fence:
            for rx, what in IN_FENCE_BAD:
                if rx.search(ln):
                    out.append(f"{no}行目: 原稿の囲みの中に{what}。囲みの中は題と1行1文のナレーションだけ（F-098）")
                    break
            continue
        details += low.count("<details") - low.count("</details>")
        if details <= 0 and TABLE.match(ln):
            out.append(f"{no}行目: 表が <details> の外にある。原稿は囲みの字で並べ、表は <details> に畳む（F-098）")
    return out


# ---------- 入口 ----------

def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="出す前の関所（帳面の投稿・進めかたの指摘）")
    ap.add_argument("cmd", choices=("post", "issue-text", "approval", "audit"))
    ap.add_argument("target", nargs="?")
    ap.add_argument("--edit")
    ap.add_argument("--rounds-why")
    a = ap.parse_args(argv)
    if a.cmd == "audit":
        sys.path.insert(0, str(HERE))
        import posted  # noqa: E402
        try:
            rows = posted.load()
        except posted.Broken as e:
            print(f"読めない: {e}")
            return 2
        miss, stale = ig_missing(rows), stale_pending(rows)
        for p in miss:
            print(f"✕ instagram: {p} は YouTube・TikTok に出たのに Instagram の done が無い（F-090）")
        for r in stale:
            print(f"△ one: {r['plan']} の {r['place']} が {r['at']} から pending のまま（投稿先で見て mark --done か --again）")
        print(f"結果: Instagram の抜け {len(miss)}・止まった pending {len(stale)}")
        return 1 if miss else 0
    if not a.target:
        ap.error("読むものが要る")
    if a.cmd == "approval":
        cid, why = approval(a.target)
        print(why or f"○ コメント {cid} はあやと本人の言葉（承認に数えてよい。中身は担当が読む）")
        return 1 if why else 0
    try:
        body = Path(a.target).read_text(encoding="utf-8")
        probs = plain_why(body) if a.cmd == "issue-text" else send_problems(json.loads(body), Path(a.edit) if a.edit else None,
                                                                             a.rounds_why)
    except (OSError, ValueError) as e:
        print(f"読めない: {e}")
        return 2
    for p in probs:
        print(f"✕ {p}")
    print(f"結果: ✕ {len(probs)}")
    return 1 if probs else 0


if __name__ == "__main__":
    sys.exit(main())
